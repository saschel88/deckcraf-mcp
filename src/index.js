function делатьStart(а, доп) {
  const стиль = арг(а, 'style', 'стиль');
  if (!стиль) return отказ('Не указан стиль. Передайте style — один из: ' + СТИЛИ.join(', '));
  if (!СТИЛИ.includes(стиль)) return отказ(`Стиля «${стиль}» нет. Доступны: ${СТИЛИ.join(', ')}`);

  СЕССИИ.set(ключСессии(доп), { стиль });
  process.stderr.write(`сессия ${ключСессии(доп)}: стиль ${стиль}\n`);

  return ответ({
    'стиль': стиль,
    'зафиксирован': true,
    'спецификация': СПЕЦ_СТИЛЕЙ[стиль],
    'фон': фонДля(стиль),
    'элементов_доступно': [...ЭЛЕМЕНТЫ.values()].filter(э => допустимые(э.ид).includes(стиль)).length,
    'дальше': 'find — подобрать элемент, describe — получить описание, draw — отрисовать'
  });
}

/* Каталог намеренно не требует выбранного стиля: «что у вас есть» спрашивают
   до того, как выбирают стиль, а не после. Если стиль всё же зафиксирован,
   добавляем доступность — у шести переходных слайдов она ограничена. */
function делатьCatalog(а, доп) {
  const стиль = выбранный(доп);
  const раздел = арг(а, 'category', 'раздел');
  if (раздел && !CATS.some(([к]) => к === раздел))
    return отказ(`Раздела «${раздел}» нет. Есть: ${CATS.map(([к]) => к).join(', ')}`);

  const разделы = CATS.filter(([к]) => !раздел || к === раздел).map(([к, список]) => ({
    'раздел': к,
    'элементов': список.length,
    'элементы': список.map(([ид]) => {
      const э = ЭЛЕМЕНТЫ.get(ид);
      return {
        'id': ид,
        'название': э.название,
        'назначение': э.спец?.['назначение'] ?? 'не описано',
        'принимает_данные': э.отрисовка.length >= 2,
        /* Форма поля одна на все инструменты — объект либо null, и ключ
           стоит всегда, когда стиль выбран. Раньше catalog отдавал строку
           и на годной паре ключ опускал: клиент, научившийся на describe
           читать «.почему», получал здесь undefined, а проверка «ключ есть»
           на find была истинна для каждой годной пары. Тот же дефект, что
           чинил Д-2, только заведённый не внутри ответа, а МЕЖДУ ответами. */
        ...(стиль ? { 'доступен_в_стиле': допустимые(ид).includes(стиль),
          'не_рекомендуется_в_стиле': оговоркаСтиля(ид, стиль) } : {})
      };
    })
  }));

  /* Счётчики считаем по показанному, а не по библиотеке: иначе при фильтре
     по разделу рядом стоят «всего 5» и «принимают данные 29». */
  const показаны = разделы.flatMap(р => р['элементы']);
  return ответ({
    'всего': показаны.length,
    ...(раздел ? { 'в_библиотеке_всего': ЭЛЕМЕНТЫ.size } : {}),
    'стиль': стиль,
    'принимают_данные': показаны.filter(э => э['принимает_данные']).length,
    'о_данных': 'Элемент без пометки «принимает_данные» рисуется образцовыми значениями: ' +
      'переданные данные draw примет, но в разметку они не попадут, и он об этом предупредит.',
    'разделы': разделы,
    'дальше': стиль
      ? 'describe — подробности элемента, draw — отрисовать'
      : 'styles — список стилей, start — зафиксировать стиль на всю презентацию'
  });
}

function делатьFind(а, доп) {
  const стиль = выбранный(доп);
  if (!стиль) return отказ(НЕТ_СТИЛЯ);
  const запрос = арг(а, 'query', 'запрос');
  if (!запрос) return отказ('Не указан запрос. Передайте query — что нужно показать, своими словами.');

  const найдены = искать(запрос);
  if (!найдены.length) return ответ({
    'запрос': запрос, 'кандидаты': [],
    'подсказка': 'Ничего не совпало. Попробуйте другими словами, назовите категорию или вызовите catalog и посмотрите весь состав. Категории: ' +
      CATS.map(([к]) => к).join(', ')
  });

  return ответ({
    'запрос': запрос,
    'стиль': стиль,
    'кандидаты': найдены.map(э => ({
      'id': э.ид,
      'название': э.название,
      'категория': э.категория,
      'назначение': э.спец?.['назначение'] ?? 'не описано',
      'не_применять': э.спец?.['не_применять'] ?? 'не описано',
      'доступен_в_стиле': допустимые(э.ид).includes(стиль),
      'не_рекомендуется_в_стиле': оговоркаСтиля(э.ид, стиль)
    }))
  });
}

/* Договор с проставленными пределами под выбранный стиль. Число берётся
   из библиотеки, а не из документа: в spec/elements.json записана гарантия
   на все тринадцать стилей — наименьшая из тринадцати, — а здесь стиль уже
   известен, и врать заниженным числом больше незачем. Копия поверхностная
   и своя: общий разобранный spec портить нельзя, его читают все сессии. */
function сПределами(договор, отрисовка, s) {
  if (!договор || typeof договор !== 'object') return договор;
  const из = {};
  for (const [ключ, правило] of Object.entries(договор)) {
    const тип = правило && typeof правило === 'object' && !Array.isArray(правило) ? правило['тип'] : null;
    if (тип === 'строка') { из[ключ] = сПределомСтроки(правило, отрисовка, ключ, s); continue; }
    if (тип === 'массив строк') { из[ключ] = сПределомМассива(правило, отрисовка, ключ, s); continue; }
    if (правило && правило['поля']) {
      /* Соседние числа собираются РАЗ на массив и передаются вглубь: предел
         подполя обязан быть тем же числом, что стоит в «длине» договора,
         а оно снято при худшем законном соседе. Считай describe по образцу —
         и он назвал бы 9 там, где договор обещает 7: та же ложь, только
         вошедшая в другую дверь. */
      const сосЛ = соседиМассива(правило).map(с => ({ ...с, путь: `${ключ}.${с.путь}` }));
      из[ключ] = сПодполями(правило, отрисовка, ключ, s, числаСтрок(правило['количество']), сосЛ); continue; }
    из[ключ] = правило;
  }
  return из;
}

/* Подполя массива объектов — тот же предел, тот же describe, только путь
   к полю идёт через точку. Законные числа рядов берутся у ВЕРХНЕГО массива:
   у него же в договоре стоит «количество», и именно его длина задаёт
   геометрию слота (swim.lanes.steps.label меряется по числу дорожек,
   потому что своего «количества» у шагов нет). «Строками» здесь и дальше
   зовутся ряды массива — тем же словом, что и у «массива строк» наряда 20,
   чтобы таблица в договоре читалась и разбиралась одним способом. */
function сПодполями(правило, отрисовка, путь, s, числа, соседи) {
  const поля = {};
  for (const [к, п] of Object.entries(правило['поля'] || {})) {
    if (!п || typeof п !== 'object' || Array.isArray(п)) { поля[к] = п; continue; }
    if (п['поля']) { поля[к] = сПодполями(п, отрисовка, `${путь}.${к}`, s, числа, соседи); continue; }
    const тип = String(п['тип'] || '');
    поля[к] = (тип === 'строка' || тип === 'массив')
      ? сПределомПодполя(п, отрисовка, `${путь}.${к}`, s, числа, соседи) : п;
  }
  return { ...правило, 'поля': поля };
}

/* ФОРМУ ВЫБИРАЕТ ЗАМЕР, А НЕ СПИСОК ИМЁН — правило то же, что у наряда 20,
   только исходов три, и все три различает сам замер:

   «не ограничено» — предел упёрся в ВЕРХ_ПРЕДЕЛА: поле не ужимается вовсе
                     (arrows.steps.n рисуется как передан), обрезки не бывает
                     ни при какой длине, и число тут было бы враньём;
   таблица         — предел падает с числом строк и падает МОНОТОННО: так
                     выглядит слот, ширина которого делится на их число;
   одно число      — всё остальное, по худшему из законных чисел строк.

   Немонотонный ряд — доказательство, что предел определяет не число строк:
   у funnel.levels.value ширину слота задаёт k СОСЕДНЕГО уровня, и замер
   даёт 3 → 15, 4 → 8, 5 → 11. Таблица, подписанная «строк → знаков»,
   говорила бы одно, а значила другое — тот же довод, по которому наряд 20
   не дал таблицу heat.cols. */
function сПределомПодполя(правило, отрисовка, путь, s, числа, соседи) {
  const пары = (числа || []).map(n => [n, пределЗнаков(отрисовка, путь, s, n, худшиеСоседи(отрисовка, путь, s, n, соседи))])
    .filter(([, в]) => в !== null && в !== undefined);
  if (!пары.length)
    return { ...правило, 'предел_знаков': null,
      'предел_заметка': числа ? 'в этом стиле поле подписью не рисуется'
        : 'договор не говорит, сколько строк бывает, — предел не посчитан' };
  const зн = пары.map(([, в]) => в);
  if (зн.every(в => в >= ВЕРХ_ПРЕДЕЛА))
    return { ...правило, 'предел_знаков': null,
      'предел_заметка': 'обрезкой не ограничено: поле рисуется как передано, без ужатия — ' +
        `многоточия не будет ни при какой длине, но длинное значение выйдет за кромку карточки. ` +
        `Мера выше ${ВЕРХ_ПРЕДЕЛА} знаков не поднимается` };
  if (new Set(зн).size === 1)
    return { ...правило, 'предел_знаков': зн[0],
      'предел_заметка': `${зн[0]} знаков в стиле «${стильИмя(s)}» — измерено отрисовкой, а не оценено; ` +
        'число строк на предел не влияет — слот у них общей ширины' };
  const худший = Math.min(...зн);
  if (!зн.every((в, i) => i === 0 || в <= зн[i - 1]))
    return { ...правило, 'предел_знаков': худший,
      'предел_заметка': `${худший} знаков в стиле «${стильИмя(s)}» — измерено отрисовкой, а не оценено. ` +
        `Число строк предела не определяет: замер даёт ${пары.map(([n, в]) => `${n} → ${в}`).join(', ')}, ` +
        'ряд немонотонен — ширину слота задаёт соседнее числовое подполе, а не число строк. Дано по худшему' };
  const таблица = {};
  for (const [n, в] of пары) таблица[String(n)] = в;
  return { ...правило, 'предел_знаков': таблица,
    'предел_заметка': `предел зависит от числа строк (${пары.map(([n, в]) => `${n} → ${в}`).join(', ')}) ` +
      `в стиле «${стильИмя(s)}»: ширина слота делится на их число. Измерено отрисовкой, а не оценено` };
}

function сПределомСтроки(правило, отрисовка, ключ, s) {
  const предел = пределЗнаков(отрисовка, ключ, s);
  return предел === null || предел === undefined
    ? { ...правило, 'предел_знаков': null, 'предел_заметка': 'в этом стиле поле подписью не рисуется' }
    : { ...правило, 'предел_знаков': предел,
        'предел_заметка': `${предел} знаков в стиле «${стильИмя(s)}» — измерено отрисовкой, а не оценено; ` +
          'длиннее подпись сперва ужимается кеглем, а на полу 9 обрезается многоточием' };
}

/* Предел массива под выбранный стиль. Число строк describe не знает — оно
   известно только draw, — поэтому здесь отдаётся всё, что зависит от него:
   одно число, если законные числа строк дают один и тот же предел (так у
   одиннадцати полей из тринадцати), и таблица «строк → знаков», если разные
   (roadmap.cols и area.labels — там ширина слота делится на число строк).
   Форму выбирает не список имён, а сам замер: поле, у которого зависимость
   появится или исчезнет, сменит форму само и врать не начнёт. */
function сПределомМассива(правило, отрисовка, ключ, s) {
  const числа = числаСтрок(правило['количество']);
  const пары = (числа || []).map(n => [n, пределЗнаков(отрисовка, ключ, s, n)])
    .filter(([, в]) => в !== null && в !== undefined);
  if (!пары.length)
    return { ...правило, 'предел_знаков': null,
      'предел_заметка': числа ? 'в этом стиле поле подписью не рисуется'
        : 'договор не говорит, сколько строк бывает, — предел на строку не посчитан' };
  if (new Set(пары.map(([, в]) => в)).size === 1)
    return { ...правило, 'предел_знаков': пары[0][1],
      'предел_заметка': `${пары[0][1]} знаков на строку в стиле «${стильИмя(s)}» — измерено отрисовкой, ` +
        'а не оценено; число строк на предел не влияет — слот у них общей ширины' };
  const таблица = {};
  for (const [n, в] of пары) таблица[String(n)] = в;
  return { ...правило, 'предел_знаков': таблица,
    'предел_заметка': `предел на строку зависит от числа строк (${пары.map(([n, в]) => `${n} → ${в}`).join(', ')}) ` +
      `в стиле «${стильИмя(s)}»: ширина слота делится на их число. Измерено отрисовкой, а не оценено` };
}

function делатьDescribe(а, доп) {
  const стиль = выбранный(доп);
  if (!стиль) return отказ(НЕТ_СТИЛЯ);
  const э = ЭЛЕМЕНТЫ.get(String(арг(а, 'id')));
  if (!э) return отказ(`Элемента «${арг(а, 'id')}» нет. Подберите его через find.`);

  const с = э.спец;
  if (!с || !с['композиция']) return ответ({
    'id': э.ид, 'название': э.название,
    'описание': 'не готово',
    'нарисовать_можно': true
  });

  return ответ({
    'id': э.ид,
    'название': э.название,
    'иначе_называют': с['иначе_называют'] ?? null,
    'категория': э.категория,
    'назначение': с['назначение'],
    'применять': с['применять'],
    'не_применять': с['не_применять'],
    'композиция': с['композиция'],
    'данные': сПределами(с['данные'], э.отрисовка, ST[стиль]),
    'пример_данных': э.образец,
    'пример_данных_оговорка': э.оговорка,
    'принимает_данные': э.отрисовка.length >= 2,
    'заметки_по_стилям': с['заметки'] ?? null,
    'стиль': стиль,
    'доступен_в_стиле': допустимые(э.ид).includes(стиль),
    'не_рекомендуется_в_стиле': оговоркаСтиля(э.ид, стиль),
    'фон': фонДля(стиль),
    'запреты_стиля': СПЕЦ_СТИЛЕЙ[стиль]['нельзя'],
    'инварианты': ПРАВИЛА['геометрия']
  });
}

function делатьDraw(а, доп) {
  /* Стиль берём поштучный, если передан: при одном сервере на всех агентов
     разделяемая ячейка переписывается соседом, и явное указание — единственный
     способ отрисовать наверняка. Состояние сессии при этом не трогаем. */
  const сессионный = выбранный(доп);
  const явный = арг(а, 'style', 'стиль');
  if (явный && !СТИЛИ.includes(явный)) return отказ(`Стиля «${явный}» нет. Доступны: ${СТИЛИ.join(', ')}`);
  const стиль = явный || сессионный;
  if (!стиль) return отказ(НЕТ_СТИЛЯ);
  const э = ЭЛЕМЕНТЫ.get(String(арг(а, 'id')));
  if (!э) return отказ(`Элемента «${арг(а, 'id')}» нет. Подберите его через find.`);
  if (!допустимые(э.ид).includes(стиль))
    return отказ(`Элемент «${э.ид}» в стиле «${стиль}» не отрисовывается. Доступные стили: ${допустимые(э.ид).join(', ')}`);

  const данные = арг(а, 'data', 'данные');
  const s = ST[стиль];
  const предупреждения = [];

  /* Смешение стилей в одной колоде запретить нечем — start и так позволяет
     переключаться. Зато его можно сделать видимым. */
  if (явный && сессионный && явный !== сессионный)
    предупреждения.push(`отрисовано в «${явный}», а на сессию зафиксирован «${сессионный}»: ` +
      'в одной презентации стили смешивать нельзя');

  /* Пара, объявленная библиотекой негодной. Отказа тут нет нарочно: правило
     проекта — элемент рисует всегда, проверки отрисовку не блокируют. Молчать
     тоже нельзя, а до наряда 28 draw именно молчал: причина исключения лежала
     прозой внутри «заметок» describe и до draw не доходила никак. */
  const негодна = неРекомендуется(э.ид, стиль);
  if (негодна)
    предупреждения.push(`пара «${э.ид}» × «${стиль}» объявлена в договоре негодной: ${негодна}. ` +
      'Отрисовано всё равно — проверки отрисовку не блокируют, — но под ту же мысль лучше взять ' +
      'другой элемент: стиль в презентации один и меняться не должен');

  /* Третий источник сообщений о данных. Первые два — сверитьДанные (состав
     полей) и шесть проверок (готовая разметка) — про смысл значений не знают
     ничего, и между ними была пустота: элемент видел, что итог не сходится
     или что значение зажато, а сказать об этом ему было нечем. Сборщик —
     обычный массив третьим аргументом: он не ломает ни одного прежнего вызова
     и, в отличие от поля на функции, переживает параллельную работу. */
  const записи = [];

  let svg;
  try { svg = данные ? э.отрисовка(s, данные, записи) : э.отрисовка(s); }
  catch (e) {
    process.stderr.write(`сбой отрисовки ${стиль}/${э.ид}: ${e.stack}\n`);
    return отказ(`Отрисовка «${э.ид}» в стиле «${стиль}» не удалась: ${e.message}`);
  }

  /* Применились ли данные, определяем сличением с образцом: если элемент
     второй аргумент игнорирует, разметка выйдет прежней. Так сервер не надо
     трогать по мере того, как элементы учатся принимать данные */
  if (данные) {
    предупреждения.push(...сверитьДанные(э.спец?.['данные'], данные, э.отрисовка, s));
    if (svg === э.отрисовка(s))
      предупреждения.push('данные приняты, но элемент отрисован образцовыми значениями: ' +
        'его функция отрисовки данные пока не принимает');

    /* Частичная подача. Записи уходят в «замечания» и проговариваются словами
       вместе с прочими — отдельного канала им не нужно. Сводка идёт первой
       строкой: перечень слотов важнее любого из них по отдельности, потому
       что вопрос у автора один — «что тут не моё». */
    const подмены = дополненоОбразцом(svg, э.образец, данные, записи);
    if (подмены.length) {
      предупреждения.push(`дополнено образцом: слотов ${подмены.length} — в разметке стоят ` +
        'значения библиотеки, а не переданные, и чужие цифры выглядят достоверно. ' +
        'Каждый слот назван поимённо ниже и в «замечаниях»');
      записи.push(...подмены);
    }
  }

  /* «Перенесены на несколько строк» называло конкретный механизм переноса,
     которого в библиотеке нет: подписи не заворачиваются через tspan,
     а элемент растёт, когда переданного содержимого (рядов, шагов, пунктов)
     больше, чем в образце, и стандартных 190px не хватает по вертикали.
     У bars холст растёт от пятого ряда при упавшем кегле — переноса строк
     там вовсе не бывает, а старый текст отправлял автора искать
     несуществующие двухстрочные подписи. Формулировка ниже не называет
     причину — она верна для роста от лишних рядов, лишних шагов и любого
     другого источника разом. */
  const размер = холст(svg);
  if (размер.высота > 190)
    предупреждения.push(`холст вырос до ${размер.высота}px: содержимого больше, чем умещается в стандартных 190px`);

  /* Отрисовка ужимает кегль, а когда упирается в пол — режет строку многоточием.
     В образцовых отрисовках всех 676 пар многоточия нет ни одного, так что
     знак однозначно указывает на потерянный текст. */
  const обрезаны = [...svg.matchAll(/>([^<>]*…)</g)].map(m => m[1].trim()).filter(Boolean);
  if (обрезаны.length)
    предупреждения.push(`подписи не поместились и обрезаны: ${обрезаны.join(' / ')}`);

  const кегли = [...svg.matchAll(/font-size="([\d.]+)"/g)].map(m => Number(m[1]));
  if (кегли.length && Math.min(...кегли) < 8)
    предупреждения.push(`минимальный кегль в элементе ${Math.min(...кегли)} — подпись ужата, чтобы влезть`);

  /* Замечания элемента проговариваются словами наравне с прочими — и уходят
     машиночитаемыми отдельным полем. Строка нужна человеку, запись — модели-
     сборщику: из «levels[1].label требует 96.4 при доступных 78.0» видно
     и поле, и насколько сокращать, а из «подписи обрезаны» не видно ничего. */
  предупреждения.push(...записи.map(словами));

  предупреждения.push(...проверить(svg, s).map(з => `${з.проверка}: ${з.сообщение}`));

  return ответ({
    'svg': svg,
    'стиль': стиль,
    'стиль_взят': явный ? 'из запроса' : 'из состояния сессии',
    'холст': размер,
    'фон': фонДля(стиль),
    'предупреждения': предупреждения,
    'замечания': записи
  });
}

/* ══════ СЕРВЕР ══════ */

const сервер = new Server(
  { name: 'deckcraft-svg-library', version: '1.0.0' },
  { capabilities: { tools: {} } }
);

сервер.setRequestHandler(ListToolsRequestSchema, async () => ({ tools: ИНСТРУМЕНТЫ }));

сервер.setRequestHandler(CallToolRequestSchema, async (запрос, доп) => {
  const { name, arguments: а } = запрос.params;
  try {
    switch (name) {
      case 'styles':   return делатьStyles();
      case 'start':    return делатьStart(а, доп);
      case 'catalog':  return делатьCatalog(а, доп);
      case 'find':     return делатьFind(а, доп);
      case 'describe': return делатьDescribe(а, доп);
      case 'draw':     return делатьDraw(а, доп);
      default:         return отказ(`Инструмента «${name}» нет. Доступны: ${ИНСТРУМЕНТЫ.map(и => и.name).join(', ')}`);
    }
  } catch (e) {
    process.stderr.write(`сбой в ${name}: ${e.stack}\n`);
    return отказ(`Внутренняя ошибка в «${name}»: ${e.message}`);
  }
});

const транспорт = new StdioServerTransport();
await сервер.connect(транспорт);
process.stderr.write(`deckcraft: ${ЭЛЕМЕНТЫ.size} элементов, ${СТИЛИ.length} стилей, транспорт stdio\n`);
