/* ── поиск ──
   Русская морфология сводится к сравнению основ: «воронка» и «воронку»
   совпадают по первым пяти знакам. Точности словаря это не заменяет,
   но выбор между 52 элементами закрывает */
const слова = с => String(с).toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я0-9]+/).filter(w => w.length > 2);

const основа = w => w.slice(0, Math.max(4, Math.min(5, w.length)));
/* Основу не тронули. У слова из четырёх-пяти букв основа равна слову
   целиком — падеж делает его чужим («цифра»/«цифру», «одна»/«одну»), но
   сузить основу для этой длины оказалось дороже, чем кажется: опробованы
   и измерены (tools/find-check.js, оба набора) три отдельных варианта —
   отсекатель типовых окончаний из тридцати с лишним, тот же отсекатель
   только по гласным, единая основа в четыре знака для слов любой
   длины — и все три просаживали хотя бы один набор относительно 15/25
   и 7/15 (например, «доля» после отсечения «я» превращалась в «дол» и
   совпадала с «должность»). Полноценного стеммера здесь нет и не будет,
   пока проба не покажет иначе.

   Вместо сужения — добавка: слова одной длины, различающиеся только
   последней буквой, — типовая пара падежных окончаний («-а»/«-у»
   и подобные). Она не пересекается с уже работающим сравнением основ,
   а только достраивает его, поэтому ничего из того, что находилось
   раньше, найтись перестать не может — проверено по всем 40 запросам
   пробы: ни один переход из «первым» в «мимо». */
const однаБуква = (a, b) => a.length === b.length && a.length >= 4 && a.slice(0, -1) === b.slice(0, -1);
const созвучны = (a, b) => a === b
  || (a.length >= 4 && b.length >= 4 && (a.startsWith(основа(b)) || b.startsWith(основа(a))))
  || однаБуква(a, b);

function поле(значение) {
  if (значение == null) return '';
  if (typeof значение === 'string') return значение;
  if (Array.isArray(значение)) return значение.join(' ');
  return Object.keys(значение).join(' ') + ' ' + Object.values(значение).map(поле).join(' ');
}

/* «не_применять» — не хвала элементу, а словарь «ситуация → к кому отправить
   вместо него»: {"нужны сроки": "дорожная карта"}. Раньше совпадение
   с ключом поднимало САМ элемент — поэтому на «сроки» вылезал cicd, у
   которого в противопоказаниях как раз написано «нужны сроки → дорожная
   карта». Совпадение с ключом должно поднимать элемент, названный
   в значении, а не владельца записи. */
const ИМЕНА = [...ЭЛЕМЕНТЫ.values()]
  .map(э => [э.ид, String(э.название).toLowerCase()])
  .sort((a, b) => b[1].length - a[1].length);

/* Из 144 записей 124 значения — точное название элемента целиком
   («три факта», «waterfall»). Остальные 20 — проза для человека
   («treemap или кольцевая», «разбить на два слайда»): в них ищем имя
   элемента внутри строки, длинные имена раньше коротких — иначе
   «таймлайн» сработает внутри уже найденного «таймлайн карточками».
   Если значение не называет ни одного элемента — совет адресован
   человеку, а не поиску, и балла не получает никто. Элемент, которому
   принадлежит запись, из целей исключается — иначе «прогресс-бары —
   радар выродится» в противопоказаниях radar поднимал бы сам radar. */
function целиПереадресации(значение, исключить) {
  const т = String(значение || '').trim().toLowerCase();
  if (!т) return [];
  const точно = ИМЕНА.find(([, имя]) => имя === т);
  if (точно) return точно[0] === исключить ? [] : [точно[0]];
  const цели = [];
  let остаток = т;
  for (const [ид, имя] of ИМЕНА) {
    if (ид === исключить) continue;
    if (остаток.includes(имя)) { цели.push(ид); остаток = остаток.split(имя).join(' '); }
  }
  return цели;
}

function искать(запрос) {
  const цель = слова(запрос);
  if (!цель.length) return [];
  const баллы = new Map();
  const начислить = (ид, б) => баллы.set(ид, (баллы.get(ид) || 0) + б);

  for (const э of ЭЛЕМЕНТЫ.values()) {
    const с = э.спец || {};
    const веса = [
      [3, поле(э.название)],
      [3, поле(с['назначение'])],
      [2, поле(с['применять'])],
      [1, поле(э.категория)]
    ];
    for (const [вес, текст] of веса) {
      const где = слова(текст);
      for (const т of цель) if (где.some(w => созвучны(w, т))) начислить(э.ид, вес);
    }

    const переадресация = с['не_применять'];
    if (переадресация && typeof переадресация === 'object')
      for (const [ключ, значение] of Object.entries(переадресация)) {
        const где = слова(ключ);
        if (!цель.some(т => где.some(w => созвучны(w, т)))) continue;
        for (const ид of целиПереадресации(значение, э.ид)) начислить(ид, 1);
      }
  }

  const оценки = [...баллы.entries()]
    .map(([ид, балл]) => ({ балл, э: ЭЛЕМЕНТЫ.get(ид) }))
    .sort((a, b) => b.балл - a.балл || a.э.ид.localeCompare(b.э.ид));
  return оценки.slice(0, 3).map(о => о.э);
}

/* ── количественные рамки договора ──
   В spec/elements.json встречаются четыре записи: «3», «2–5», «ровно 4»
   и «0 или 2». Разбираем все: лишнее отрисовка молча отбрасывает,
   и без этой проверки потеря данных ничем себя не выдаёт. */
function рамки(текст) {
  const с = String(текст || '').trim();
  if (!с) return null;
  const или = с.match(/^(\d+)\s*или\s*(\d+)$/i);
  if (или) return { макс: +или[2], годится: n => n === +или[1] || n === +или[2], словами: `${или[1]} или ${или[2]}` };
  const вилка = с.match(/(\d+)\s*[–—-]\s*(\d+)/);
  if (вилка) return { макс: +вилка[2], годится: n => n >= +вилка[1] && n <= +вилка[2], словами: `${вилка[1]}–${вилка[2]}` };
  const до = с.match(/^до\s*(\d+)$/i);
  if (до) return { макс: +до[1], годится: n => n >= 1 && n <= +до[1], словами: `до ${до[1]}` };
  const одно = с.match(/(\d+)/);
  if (одно) return { макс: +одно[1], годится: n => n === +одно[1], словами: `ровно ${одно[1]}` };
  return null;
}

/* ── проверка данных против договора ──
   Договор в spec/elements.json написан для человека, а не как JSON Schema,
   поэтому сверяем то, что поддаётся: состав полей и грубый тип */
function сверитьДанные(договор, данные) {
  const замечания = [];
  if (!данные || typeof данные !== 'object') return замечания;
  if (!договор || typeof договор !== 'object') return замечания;

  /* Не всякий ключ внутри «данные» — параметр. Описательные ключи вроде
     «структура» (неизменяемое устройство) или «$заметка» (пояснение
     вёрстки) передавать нельзя и не нужно — они не входят в договор
     о том, что можно передать, и проверке не подлежат ни в одну сторону:
     ни как обязательные, ни как разрешённые. Признак параметра —
     значение-объект с «тип» или «поля». Ключи на «$» описательные
     по соглашению спецификации всегда. */
  const параметрЛи = (ключ, правило) =>
    !ключ.startsWith('$') && !!правило && typeof правило === 'object' && !Array.isArray(правило) &&
    ('тип' in правило || 'поля' in правило);

  const известные = Object.entries(договор).filter(([к, п]) => параметрЛи(к, п)).map(([к]) => к);
  for (const ключ of Object.keys(данные))
    if (!известные.includes(ключ))
      замечания.push(`поле «${ключ}» договором не предусмотрено; в договоре есть: ${известные.join(', ')}`);

  for (const [ключ, правило] of Object.entries(договор)) {
    if (!параметрЛи(ключ, правило)) continue;

    const з = данные[ключ];
    if (з === undefined) {
      if (правило['необязательно'] !== true)
        замечания.push(`поле «${ключ}» не передано — будет взято из образца`);
      continue;
    }
    const тип = String(правило?.['тип'] || '');
    if (тип.startsWith('массив') && !Array.isArray(з)) замечания.push(`поле «${ключ}» ждёт массив, пришло ${typeof з}`);
    if (тип === 'строка' && typeof з !== 'string') замечания.push(`поле «${ключ}» ждёт строку, пришло ${typeof з}`);
    if (тип === 'число' && typeof з !== 'number') замечания.push(`поле «${ключ}» ждёт число, пришло ${typeof з}`);
    if (Array.isArray(з)) {
      const р = рамки(правило?.['количество']);
      if (р && !р.годится(з.length))
        замечания.push(з.length > р.макс
          ? `«${ключ}»: передано ${з.length}, договор требует ${р.словами} — лишние ${з.length - р.макс} в разметку не попадут`
          : `«${ключ}»: передано ${з.length}, договор требует ${р.словами} — вёрстка рассчитана на другое число`);
    }
    const длина = /(\d+)/.exec(String(правило?.['длина'] || ''));
    if (длина && typeof з === 'string' && з.length > Number(длина[1]))
      замечания.push(`«${ключ}»: ${з.length} знаков при договорных ${длина[1]} — подпись будет ужата или перенесена`);

    /* Массив строк тоже подчиняется «длине», но раньше её не проверял —
       длина проверялась только у скалярной строки. У heat.rows предел
       тесен (3 знака): «нед1»…«нед4» из отчёта превышают его на один знак
       каждая, отрисовка режет их до общего «нед» — различие, которым
       подписи и были, теряется молча. Предупреждаем об обеих бедах: что
       строка длиннее предела и что после обрезки строки совпали. */
    if (длина && тип === 'массив строк' && Array.isArray(з) && з.every(п => typeof п === 'string')) {
      const предел = Number(длина[1]);
      const длинные = з.filter(п => п.length > предел);
      if (длинные.length)
        замечания.push(`«${ключ}»: ${длинные.length} из ${з.length} строк длиннее договорных ${предел} знаков ` +
          `(напр. «${длинные[0]}», ${длинные[0].length}) — подпись будет ужата`);
      const после = з.map(п => п.slice(0, предел));
      const совпавшие = [...new Set(после.filter((c, i) => после.indexOf(c) !== i))];
      if (совпавшие.length && new Set(после).size < new Set(з).size)
        замечания.push(`«${ключ}»: после обрезки до ${предел} знаков подписи совпадают ` +
          `(${совпавшие.join(', ')}) — то, чем они различались, терялось`);
    }
  }
  return замечания;
}

