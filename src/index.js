#!/usr/bin/env node
/* ══════ MCP-СЕРВЕР БИБЛИОТЕКИ SVG-ЭЛЕМЕНТОВ ══════
   Пять инструментов, транспорт stdio, один стиль на сессию.

   Имена инструментов латинские: Anthropic API принимает имя только по
   шаблону ^[a-zA-Z0-9_-]{1,64}$, кириллица до Claude Desktop не доедет.
   Всё, что видит человек, — заголовки, описания и ключи ответа — русское,
   как в ТЗ. Русские имена параметров принимаются как синонимы.

   Стиль хранится не в переменной модуля, а в карте по ключу сессии:
   при переезде на HTTP ключей станет по числу подключений, и переписывать
   инструменты не придётся.

   stdout занят протоколом. Всё, что нужно сказать человеку, идёт в stderr. */

import { readFileSync } from 'node:fs';
import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { ListToolsRequestSchema, CallToolRequestSchema } from '@modelcontextprotocol/sdk/types.js';

import { ST, ALLOW } from './engine.js';
import { CATS } from './elements.js';
import { проверить, холст } from './checks.js';

const чтение = имя => JSON.parse(readFileSync(new URL(`../spec/${имя}.json`, import.meta.url), 'utf8'));
const СПЕЦ_СТИЛЕЙ   = чтение('styles')['стили'];
const СПЕЦ_ЭЛЕМЕНТОВ = чтение('elements')['элементы'];
const ПРАВИЛА       = чтение('rules');
const ТОКЕНЫ        = чтение('tokens');

/* ── каталог ──
   spec/styles.json — источник истины по составу: там ровно 13 стилей.
   В ST есть четырнадцатый, iso, снятый с производства, — он не публикуется. */
const СТИЛИ = Object.keys(СПЕЦ_СТИЛЕЙ).filter(k => ST[k]);

const ЭЛЕМЕНТЫ = new Map();
for (const [категория, список] of CATS)
  for (const [ид, название, отрисовка] of список)
    ЭЛЕМЕНТЫ.set(ид, { ид, название, категория, отрисовка, спец: null });

for (const с of Object.values(СПЕЦ_ЭЛЕМЕНТОВ)) {
  const э = ЭЛЕМЕНТЫ.get(с.id);
  if (э) э.спец = с;
  else process.stderr.write(`внимание: в spec/elements.json описан «${с.id}», которого нет в elements.js\n`);
}
for (const э of ЭЛЕМЕНТЫ.values())
  if (!э.спец) process.stderr.write(`внимание: элемент «${э.ид}» отрисовывается, но не описан в spec/elements.json\n`);

/* Матрица совместимости заполнена только для переходных слайдов;
   для остальных ограничений нет — годятся все тринадцать */
const допустимые = ид => ALLOW[ид] || СТИЛИ;

/* Стили, несущие собственный фоновый слой */
const НЕСУЩИЕ_ФОН = ПРАВИЛА['фон_и_размещение']['три_вида_отношения_к_фону']['несущие_фон']['стили'];

/* ── состояние сессии ── */
const СЕССИИ = new Map();
const ключСессии = доп => доп?.sessionId ?? 'stdio';
const выбранный = доп => СЕССИИ.get(ключСессии(доп))?.стиль ?? null;

/* ── помощники ── */
const арг = (а, ...имена) => имена.map(и => а?.[и]).find(з => з !== undefined);
const ответ = о => ({ content: [{ type: 'text', text: JSON.stringify(о, null, 2) }] });
const отказ = текст => ({ content: [{ type: 'text', text: текст }], isError: true });

const НЕТ_СТИЛЯ = 'Стиль не выбран. Сначала вызовите start и зафиксируйте один стиль на всю презентацию — ' +
  'смешивать стили в одной колоде нельзя. Список стилей отдаёт styles.';

/* Требования к фону выбранного стиля в том виде, в каком их ждёт ТЗ */
function фонДля(стиль) {
  const т = СПЕЦ_СТИЛЕЙ[стиль]['требования_к_фону'] || {};
  const части = [];
  if (т['светлота']) части.push(`светлота ${т['светлота']}`);
  if (т['насыщенность']) части.push(`насыщенность ${т['насыщенность']}`);
  return {
    требуется: части.join(', ') || 'ограничений нет',
    свой_несёт: НЕСУЩИЕ_ФОН.includes(стиль),
    снимать_фон: т['снимать_фон'] || 'не указано',
    подробно: т
  };
}

/* ── поиск ──
   Русская морфология сводится к сравнению основ: «воронка» и «воронку»
   совпадают по первым пяти знакам. Точности словаря это не заменяет,
   но выбор между 52 элементами закрывает */
const слова = с => String(с).toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я0-9]+/).filter(w => w.length > 2);
const основа = w => w.slice(0, Math.max(4, Math.min(5, w.length)));
const созвучны = (a, b) => a === b || (a.length >= 4 && b.length >= 4 && (a.startsWith(основа(b)) || b.startsWith(основа(a))));

function поле(значение) {
  if (значение == null) return '';
  if (typeof значение === 'string') return значение;
  if (Array.isArray(значение)) return значение.join(' ');
  return Object.keys(значение).join(' ') + ' ' + Object.values(значение).map(поле).join(' ');
}

function искать(запрос) {
  const цель = слова(запрос);
  if (!цель.length) return [];
  const оценки = [];
  for (const э of ЭЛЕМЕНТЫ.values()) {
    const с = э.спец || {};
    const веса = [
      [3, поле(э.название)],
      [3, поле(с['назначение'])],
      [2, поле(с['применять'])],
      [1, поле(э.категория)],
      [1, поле(с['не_применять'])]
    ];
    let балл = 0;
    for (const [вес, текст] of веса) {
      const где = слова(текст);
      for (const т of цель) if (где.some(w => созвучны(w, т))) балл += вес;
    }
    if (балл > 0) оценки.push({ балл, э });
  }
  оценки.sort((a, b) => b.балл - a.балл || a.э.ид.localeCompare(b.э.ид));
  return оценки.slice(0, 3).map(о => о.э);
}

/* ── проверка данных против договора ──
   Договор в spec/elements.json написан для человека, а не как JSON Schema,
   поэтому сверяем то, что поддаётся: состав полей и грубый тип */
function сверитьДанные(договор, данные) {
  const замечания = [];
  if (!данные || typeof данные !== 'object') return замечания;
  if (!договор || typeof договор !== 'object') return замечания;

  const известные = Object.keys(договор);
  for (const ключ of Object.keys(данные))
    if (!известные.includes(ключ))
      замечания.push(`поле «${ключ}» договором не предусмотрено; в договоре есть: ${известные.join(', ')}`);

  for (const [ключ, правило] of Object.entries(договор)) {
    const з = данные[ключ];
    if (з === undefined) {
      if (!правило || правило['необязательно'] !== true)
        замечания.push(`поле «${ключ}» не передано — будет взято из образца`);
      continue;
    }
    const тип = String(правило?.['тип'] || '');
    if (тип.startsWith('массив') && !Array.isArray(з)) замечания.push(`поле «${ключ}» ждёт массив, пришло ${typeof з}`);
    if (тип === 'строка' && typeof з !== 'string') замечания.push(`поле «${ключ}» ждёт строку, пришло ${typeof з}`);
    if (тип === 'число' && typeof з !== 'number') замечания.push(`поле «${ключ}» ждёт число, пришло ${typeof з}`);
    const длина = /(\d+)/.exec(String(правило?.['длина'] || ''));
    if (длина && typeof з === 'string' && з.length > Number(длина[1]))
      замечания.push(`«${ключ}»: ${з.length} знаков при договорных ${длина[1]} — подпись будет ужата или перенесена`);
  }
  return замечания;
}

