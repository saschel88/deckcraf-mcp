/* ══════ ШЕСТЬ ПРОВЕРОК ══════
   Перенесены из checks/*.py:
     check.py    → разметка, контраст, тёмный на поле
     measure.py  → нижний отступ
     gap2.py     → зазор между подписью и фигурой
     inner.py    → отступ и центровка текста внутри фигуры
   Пороги и обоснования — spec/rules.json.

   Модуль чистый: ни состояния, ни ввода-вывода. Разбор идёт по строке SVG
   тем же способом, что и в питоновских образцах, — регулярным выражением,
   а не деревом: элементы отдают плоский набор узлов без вложенности. */

import { PAD, lumOf } from './engine.js';

/* Пороги. Каждый родился после найденного дефекта, см. spec/rules.json */
export const ПОРОГИ = {
  нижний_отступ:        16,    // px до нижней кромки карточки
  зазор_подпись_фигура: 10,    // px между отдельной подписью и фигурой над ней
  отступ_в_фигуре:       4,    // px сверху и снизу внутри блока
  перекос_в_фигуре:      3,    // px разницы между верхним и нижним отступом
  контраст:              0.20, // разница светлоты подписи и заливки под ней
  светлота_на_поле:      0.60  // минимум для текста на фоне у стилей без панели
};

/* Метрики из spec/tokens.json. При смене шрифта поедут все четыре проверки.
   Ширина знака — тот же счёт, что и мера в src/elements.js:44-51, и это
   не совпадение, а обязанность. Двойник обязан следовать за библиотекой,
   иначе проверки 7 и 8 начнут мерить не так, как она рисует, и перестанут
   ловить именно то, ради чего заведены. Шкал две, как и там:
   четыре класса на пропорциональном семействе и единая ширина знака
   на моноширинном (обоснование — в комментарии к мере, не повторяю).
   Регистр здесь гадать не нужно — проверка смотрит на готовую разметку,
   где t() свою работу уже сделал; а вот СЕМЕЙСТВО тут читается легче,
   чем в элементах: font-family стоит атрибутом на каждом <text>,
   и слепых вызовов, в которых стиль неизвестен, у проверок нет. */
const ШИР = { прописная: 0.73, цифра: 0.556, пробел: 0.28, прочее: 0.55 };
const ШИР_МОНО = 0.55;
const моноширинный = ff => /mono/i.test(String(ff || ''));
const классЗнака = c => /[A-ZА-ЯЁ]/.test(c) ? ШИР.прописная
  : /[0-9]/.test(c) ? ШИР.цифра : c === ' ' ? ШИР.пробел : ШИР.прочее;
const ВЕРХ = 0.72, НИЗ = 0.22;

/* Стили, которым отдельные проверки не предъявляются, — с причиной */
const ДЕКОР_ЗА_КРОМКОЙ = ['glass', 'aurora', 'memphis', 'brutal']; // пятна, конфетти, смещённая тень
const БЕЗ_ЗАЗОРА       = ['memphis'];                             // конфетти лежит поверх намеренно
const БЕЗ_ЦЕНТРОВКИ    = ['brutal'];                              // тень смещена, блок не совпадает с рамкой

/* ── разбор ── */

const ТЕГИ = /<(rect|circle|ellipse|polygon|line|text)\b([^>]*)>([^<]*)/g;

function атрибуты(строка) {
  const о = {};
  for (const m of строка.matchAll(/([a-z-]+)="([^"]*)"/g)) о[m[1]] = m[2];
  return о;
}

/* Плоский список узлов: тег, атрибуты, собственный текст, позиция в строке.
   Позиция нужна порядку отрисовки: заливка под подписью — та, что выведена раньше */
export function разобрать(svg) {
  const узлы = [];
  for (const m of String(svg).matchAll(ТЕГИ))
    узлы.push({ тег: m[1], а: атрибуты(m[0]), текст: m[3] || '', и: m.index });
  return узлы;
}

/* Габарит фигуры: [левый, верхний, правый, нижний] либо null, если не считается */
export function габарит(тег, а) {
  const ч = k => Number(а[k]);
  if (тег === 'rect')    return [ч('x'), ч('y'), ч('x') + ч('width'), ч('y') + ч('height')];
  if (тег === 'circle')  return [ч('cx') - ч('r'), ч('cy') - ч('r'), ч('cx') + ч('r'), ч('cy') + ч('r')];
  if (тег === 'ellipse') return [ч('cx') - ч('rx'), ч('cy') - ч('ry'), ч('cx') + ч('rx'), ч('cy') + ч('ry')];
  if (тег === 'polygon') {
    const т = (а.points || '').trim().split(/\s+/).map(p => p.split(',').map(Number));
    if (!т.length || т.some(q => q.length < 2 || q.some(Number.isNaN))) return null;
    return [Math.min(...т.map(q => q[0])), Math.min(...т.map(q => q[1])),
            Math.max(...т.map(q => q[0])), Math.max(...т.map(q => q[1]))];
  }
  return null;
}

/* Подложка карточки: широкий и высокий прямоугольник кромку не нарушает и текст не подсвечивает */
const подложка = б => б[2] - б[0] > 250 && б[3] - б[1] > 150;

/* Полоса строки: базовая линия плюс выносные элементы */
function полоса(у) {
  const кегль = Number(у.а['font-size'] || 10);
  return { верх: Number(у.а.y) - кегль * ВЕРХ, низ: Number(у.а.y) + кегль * НИЗ, кегль };
}

/* Ширина строки. Вынесена из протяжённости отдельным именем и отдана наружу
   нарочно: мера в этом проекте разъезжалась со своим двойником трижды, и проба
   обязана иметь возможность сличить два счёта знак в знак, а не на глаз.
   Семейство берётся с самого узла — в разметке оно стоит атрибутом на каждом
   <text>, гадать не нужно. Арифметика прежняя, до знака. */
export function ширинаСтроки(текст, кегль, семейство, зазор) {
  const т = String(текст == null ? '' : текст);
  /* letter-spacing SVG добавляет после каждого знака, включая последний.
     Отрицательный не учитываем: мера обязана завышать, а не занижать. */
  const зз = Math.max(0, Number(зазор) || 0);
  const моно = моноширинный(семейство);
  return [...т].reduce((с, c) => с + (моно ? ШИР_МОНО : классЗнака(c)), 0) * кегль + зз * т.length;
}

/* Протяжённость строки по горизонтали с учётом выключки */
function протяжённость(у) {
  const x = Number(у.а.x), { кегль } = полоса(у);
  const т = у.текст || '';
  const ш = ширинаСтроки(т, кегль, у.а['font-family'], у.а['letter-spacing']);
  const як = у.а['text-anchor'];
  if (як === 'middle') return [x - ш / 2, x + ш / 2];
  if (як === 'end')    return [x - ш, x];
  return [x, x + ш];
}

/* Нижняя визуальная граница узла */
function низ(тег, а) {
  const ч = k => Number(а[k]);
  if (тег === 'text')    return ч('y') + Number(а['font-size'] || 10) * НИЗ;
  if (тег === 'line')    return Math.max(ч('y1'), ч('y2'));
  const б = габарит(тег, а);
  return б ? б[3] : null;
}

const видимаяЗаливка = а =>
  а.fill && а.fill !== 'none' && !(а['fill-opacity'] !== undefined && Number(а['fill-opacity']) <= 0.5);

/* ── 1. разметка: NaN, пропавший текст ── */
function разметка(svg, узлы) {
  const из = [];
  if (!/<text/.test(svg)) из.push({ проверка: 'разметка', сообщение: 'в элементе нет ни одной подписи' });
  const брак = svg.match(/NaN|undefined/);
  if (брак) из.push({ проверка: 'разметка', сообщение: `в разметке ${брак[0]} — координата или размер не посчитались` });

  /* Наложение строк — тот же пропавший текст, только визуально:
     сравниваются реальные полосы строк, а не расстояние между базовыми линиями */
  const строки = узлы.filter(у => у.тег === 'text').map(у => ({ ...полоса(у), x: Number(у.а.x), т: у.текст }));
  for (let i = 0; i < строки.length; i++)
    for (let j = i + 1; j < строки.length; j++) {
      const a = строки[i], b = строки[j];
      const перекрытие = Math.min(a.низ, b.низ) - Math.max(a.верх, b.верх);
      if (перекрытие > 1 && Math.abs(a.x - b.x) < 24) {
        из.push({ проверка: 'разметка', значение: перекрытие,
          сообщение: `подписи «${a.т}» и «${b.т}» налезают друг на друга на ${перекрытие.toFixed(1)}px` });
        return из;                                   // одного сообщения довольно, дальше пойдут производные
      }
    }
  return из;
}

/* ── 2. нижний отступ: расстояние до кромки карточки ── */
function нижнийОтступ(узлы, s, высота) {
  if (ДЕКОР_ЗА_КРОМКОЙ.includes(s.mode)) return [];
  const кромка = высота - PAD;
  let самыйнизкий = -Infinity, чей = null;
  for (const у of узлы) {
    if (у.а.filter) continue;                        // размытие живёт по своим правилам
    const б = у.тег === 'text' ? null : габарит(у.тег, у.а);
    if (б && подложка(б)) continue;
    const н = низ(у.тег, у.а);
    if (н === null || Number.isNaN(н)) continue;
    if (н > самыйнизкий) { самыйнизкий = н; чей = у; }
  }
  if (самыйнизкий === -Infinity) return [];
  const зазор = кромка - самыйнизкий;
  if (зазор >= ПОРОГИ.нижний_отступ) return [];
  const что = чей.тег === 'text' ? `подпись «${чей.текст}»` : чей.тег;
  return [{ проверка: 'нижний отступ', значение: зазор,
    сообщение: `до нижней кромки ${зазор.toFixed(1)}px при норме ${ПОРОГИ.нижний_отступ} — ближе всех ${что}` }];
}

/* ── 3. зазор между отдельной подписью и фигурой над ней ── */
function зазорПодписьФигура(узлы, s) {
  if (БЕЗ_ЗАЗОРА.includes(s.mode)) return [];
  const размытие = /url\(#(f-gb|f-ab|gl-blur|au-blur)\)/;

  /* фигура считается, если видна заливкой ИЛИ обводкой */
  const фигуры = узлы
    .filter(у => у.тег !== 'text' && !размытие.test(у.а.filter || '') &&
      (видимаяЗаливка(у.а) || (у.а.stroke && у.а.stroke !== 'none')))
    .map(у => ({ б: габарит(у.тег, у.а), пустая: !видимаяЗаливка(у.а) }))
    .filter(о => о.б && !о.б.some(Number.isNaN) && о.б[2] - о.б[0] <= 230);
  const заполненные = фигуры.map(о => о.б);

  const из = [];
  for (const у of узлы.filter(у => у.тег === 'text')) {
    const [x1, x2] = протяжённость(у), { верх } = полоса(у), y = Number(у.а.y);
    /* подпись внутри своей фигуры или в контурном контейнере — зазор к ней не относится */
    if (заполненные.some(б => x1 >= б[0] - 4 && x2 <= б[2] + 4 && y >= б[1] && y <= б[3] + 3)) continue;
    if (фигуры.some(о => о.пустая && x1 >= о.б[0] - 2 && x2 <= о.б[2] + 2 && y >= о.б[1] && y <= о.б[3])) continue;

    let ближайший = Infinity;
    for (const б of заполненные) {
      if (x2 < б[0] - 2 || x1 > б[2] + 2) continue;  // не над этой подписью
      const зазор = верх - б[3];
      if (зазор >= 0 && зазор < ближайший) ближайший = зазор;
    }
    if (ближайший < ПОРОГИ.зазор_подпись_фигура)
      из.push({ проверка: 'зазор подпись↔фигура', значение: ближайший,
        сообщение: `подпись «${у.текст}» стоит в ${ближайший.toFixed(1)}px от фигуры над ней при норме ${ПОРОГИ.зазор_подпись_фигура}` });
  }
  return из;
}

/* ── 4. отступ и центровка текста внутри фигуры ── */
function текстВФигуре(узлы, s) {
  if (БЕЗ_ЦЕНТРОВКИ.includes(s.mode)) return [];
  /* только блоки-строки: там вертикальная центровка и ожидается.
     подложка карточки и широкие блики отсеяны размерами */
  const блоки = узлы.filter(у => у.тег === 'rect' && у.а.fill && у.а.fill !== 'none' &&
    Number(у.а.width) > 40 && Number(у.а.width) <= 230 &&
    Number(у.а.height) >= 16 && Number(у.а.height) <= 34);
  const подписи = узлы.filter(у => у.тег === 'text');

  const из = [];
  for (const у of подписи) {
    const x = Number(у.а.x), { верх, низ: н } = полоса(у);
    for (const б of блоки) {
      const x1 = Number(б.а.x), y1 = Number(б.а.y);
      const x2 = x1 + Number(б.а.width), y2 = y1 + Number(б.а.height);
      if (x < x1 || x > x2) continue;
      if (н < y1 || верх > y2) continue;             // не в этом блоке
      /* многострочный блок центруется как целое, построчно его мерить нельзя */
      const сколько = подписи.filter(п => {
        const пx = Number(п.а.x);
        return пx >= x1 && пx <= x2 && полоса(п).верх >= y1 && Number(п.а.y) <= y2;
      }).length;
      if (сколько > 1) continue;

      const сверху = верх - y1, снизу = y2 - н;
      const минимум = Math.min(сверху, снизу), перекос = Math.abs(сверху - снизу);
      if (минимум < ПОРОГИ.отступ_в_фигуре || перекос > ПОРОГИ.перекос_в_фигуре)
        из.push({ проверка: 'текст в фигуре', значение: минимум,
          сообщение: `«${у.текст}» в блоке: сверху ${сверху.toFixed(1)}px, снизу ${снизу.toFixed(1)}px` +
            (минимум < ПОРОГИ.отступ_в_фигуре ? ` — отступ меньше ${ПОРОГИ.отступ_в_фигуре}` : '') +
            (перекос > ПОРОГИ.перекос_в_фигуре ? ` — перекос ${перекос.toFixed(1)}px` : '') });
    }
  }
  return из;
}

/* Заливка, лежащая под точкой привязки подписи. Побеждает выведенная позже */
function заливкаПод(узлы, у, строгая) {
  const x = Number(у.а.x), y = Number(у.а.y);
  let нашлась = null;
  for (const р of узлы) {
    if (р.тег === 'text' || р.и >= у.и) continue;    // только то, что нарисовано раньше
    const а = р.а;
    if (!а.fill || а.fill === 'none' || а.filter) continue;
    if (строгая && а['fill-opacity'] !== undefined && Number(а['fill-opacity']) <= 0.5) continue;
    const б = габарит(р.тег, а);
    if (!б || б.some(Number.isNaN) || подложка(б)) continue;
    if (x >= б[0] - 2 && x <= б[2] + 2 && y >= б[1] - 2 && y <= б[3] + 4) нашлась = а.fill;
  }
  return нашлась;
}

/* ── 5. контраст подписи против заливки под ней ── */
function контраст(узлы, s) {
  const из = [];
  for (const у of узлы.filter(у => у.тег === 'text')) {
    const под = заливкаПод(узлы, у, true);
    if (!под) continue;
    const свЗаливки = lumOf(s, под), свТекста = lumOf(s, у.а.fill);
    if (свЗаливки === null || свТекста === null) continue;   // градиент оценить нельзя
    const δ = Math.abs(свЗаливки - свТекста);
    if (δ < ПОРОГИ.контраст)
      из.push({ проверка: 'контраст', значение: δ,
        сообщение: `подпись «${у.текст}» отличается от заливки под ней на ${δ.toFixed(2)} при норме ${ПОРОГИ.контраст}` });
  }
  return из;
}

/* ── 7. фигура не пересекает кромку холста ── */
function заКромкой(узлы, s, ширина, высота) {
  if (ДЕКОР_ЗА_КРОМКОЙ.includes(s.mode)) return [];   // пятна, конфетти и смещённая тень за кромкой разрешены по спецификации
  const из = [];
  for (const у of узлы) {
    if (у.тег === 'text') continue;                   // текст меряется отдельно, ширинаТекста() ниже
    const б = габарит(у.тег, у.а);
    if (!б || б.some(Number.isNaN)) continue;
    if (б[0] < 0 || б[1] < 0 || б[2] > ширина || б[3] > высота)
      из.push({ проверка: 'за кромкой', значение: Math.max(-б[0], -б[1], б[2] - ширина, б[3] - высота),
        сообщение: `${у.тег} выходит за кромку холста: габарит [${б.map(n => n.toFixed(1)).join(', ')}] при холсте ${ширина}×${высота}` });
  }
  return из;
}

/* ── 8. ширина подписи не пересекает кромку холста ──
   Страховка, не измеритель: задача 15 уже свела превышения ширины к нулю,
   исправив пределы длины в договоре. Но обрезка и раньше проверялась
   только у текста, выровненного по краю (x + ширина ≤ кромка, это
   встроено в саму геометрию ужать()); у центрированного (text-anchor
   middle) с тем же успехом можно ошибиться при вычислении maxW —
   формула симметрична (cx ± ширина/2), и ошибка вылезет не там, где её
   ищут. 204 узла из 398 в стиле flat центрированы — почти половина
   текста библиотеки, а автоматической проверки для неё не было вовсе.
   протяжённость() уже умеет все три вида выключки (start/middle/end) —
   она и раньше считалась в зазорПодписьФигура(), здесь используется
   ради самой ширины */
function ширинаТекста(узлы, s, ширина, высота) {
  if (ДЕКОР_ЗА_КРОМКОЙ.includes(s.mode)) return [];
  const из = [];
  for (const у of узлы.filter(у => у.тег === 'text' && у.текст)) {
    const [x1, x2] = протяжённость(у);
    const { верх, низ: н } = полоса(у);
    if (x1 < -0.5 || x2 > ширина + 0.5 || верх < -0.5 || н > высота + 0.5)
      из.push({ проверка: 'за кромкой', значение: Math.max(-x1, x2 - ширина, -верх, н - высота),
        сообщение: `подпись «${у.текст}» выходит за кромку холста: габарит [${x1.toFixed(1)}, ${верх.toFixed(1)}, ${x2.toFixed(1)}, ${н.toFixed(1)}] при холсте ${ширина}×${высота}` });
  }
  return из;
}

/* ── 6. тёмный текст на поле у стилей без панели ── */
function тёмныйНаПоле(узлы, s) {
  if (s.surf !== null) return [];                    // панель есть, текст лежит на ней
  const из = [];
  for (const у of узлы.filter(у => у.тег === 'text')) {
    if (заливкаПод(узлы, у, false)) continue;        // под подписью фигура, а не поле
    const св = lumOf(s, у.а.fill);
    if (св === null || св >= ПОРОГИ.светлота_на_поле) continue;
    из.push({ проверка: 'тёмный на поле', значение: св,
      сообщение: `подпись «${у.текст}» цветом ${у.а.fill} лежит прямо на фоне со светлотой ${св.toFixed(2)} при норме ${ПОРОГИ.светлота_на_поле}` });
  }
  return из;
}

/* ── свод ──
   svg — готовая разметка, s — объект стиля из ST.
   Возвращает список замечаний; отрисовку не блокирует ни одно из них. */
export function проверить(svg, s) {
  const узлы = разобрать(svg);
  const вб = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(svg);
  const ширина = вб ? Number(вб[1]) : 300;
  const высота = вб ? Number(вб[2]) : 190;
  return [
    ...разметка(svg, узлы),
    ...нижнийОтступ(узлы, s, высота),
    ...зазорПодписьФигура(узлы, s),
    ...текстВФигуре(узлы, s),
    ...контраст(узлы, s),
    ...тёмныйНаПоле(узлы, s),
    ...заКромкой(узлы, s, ширина, высота),
    ...ширинаТекста(узлы, s, ширина, высота)
  ];
}

/* Размер холста из самой разметки: высота переменная, ширина всегда 300 */
export function холст(svg) {
  const вб = /viewBox="0 0 ([\d.]+) ([\d.]+)"/.exec(String(svg));
  return вб ? { ширина: Number(вб[1]), высота: Number(вб[2]) } : { ширина: 300, высота: 190 };
}
