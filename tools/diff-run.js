const глубже = (з, чис, стр) => {
  if (typeof з === 'number') return чис(з);
  if (typeof з === 'string') return стр ? стр(з) : з;
  if (Array.isArray(з)) return з.map(x => глубже(x, чис, стр));
  if (з && typeof з === 'object') { const о = {}; for (const [k, v] of Object.entries(з)) о[k] = глубже(v, чис, стр); return о; }
  return з;
};
const поЭлементам = (Д, f) => { const о = {}; for (const [ид, д] of Object.entries(Д)) о[ид] = f(д); return о; };

/* все строковые слоты — забиты фразой ровно объявленной в договоре длины.
   Кладём ПОВЕРХ договорных данных, а не вместо: форма набора остаётся годной,
   перечисления и числа целы, а строки достают до своего предела. */
function поПределу(Д) {
  const дог = JSON.parse(readFileSync(КОРЕНЬ + 'spec/elements.json', 'utf8'))['элементы'];
  const описи = new Map();
  for (const э of Object.values(дог)) описи.set(э.id, э['данные'] || {});
  const предел = оп => {
    if (!оп || typeof оп !== 'object') return 0;
    if (!String(оп['тип'] || '').includes('строк')) return 0;
    const m = /(\d+)/.exec(String(оп['длина'] || ''));
    return m ? +m[1] : 0;
  };
  const длинная = n => { let с = ФРАЗА; while (с.length < n) с += ' ' + ФРАЗА; return с.slice(0, n); };
  const класть = (знач, оп) => {
    if (typeof знач === 'string') { const n = предел(оп); return n ? длинная(n) : знач; }
    if (Array.isArray(знач)) return знач.map(x => класть(x, оп));
    if (знач && typeof знач === 'object') {
      const поля = оп && оп['поля'];
      const о = {};
      for (const [k, v] of Object.entries(знач)) о[k] = класть(v, поля ? поля[k] : undefined);
      return о;
    }
    return знач;
  };
  const о = {};
  for (const [ид, д] of Object.entries(Д)) о[ид] = класть(д, { 'поля': описи.get(ид) || {} });
  return о;
}

/* ══════ разбор списка пар ══════ */
function читатьСписок(файл) {
  if (!existsSync(файл)) { console.error(`НЕТ ФАЙЛА СПИСКА: ${файл}`); process.exit(1); }
  const т = readFileSync(файл, 'utf8');
  const s = new Set();
  for (const m of т.matchAll(/^\|\s*\d+\s*\|\s*([A-Za-z][\w-]*)\s*\|\s*`([\w-]+)`\s*\|/gm)) s.add(m[1] + '/' + m[2]);
  for (const m of т.matchAll(/^([a-z][\w-]*)\/([\w-]+)\s*$/gm)) s.add(m[1] + '/' + m[2]);
  return s;
}

/* ══════ чем именно отличается ══════
   «Разошлись N» — не ответ. Ответ — элемент, стиль, режим и чем разметка
   отличается: подписью, кеглем или, если ни тем ни другим, первым
   разошедшимся местом с обеих сторон. */
const ТЕКСТЫ = s => [...String(s).matchAll(/<text\b[^>]*>([\s\S]*?)<\/text>/g)].map(m => m[1]);
const КЕГЛИ = s => [...String(s).matchAll(/font-size="([^"]*)"/g)].map(m => m[1]);
const срез = (s, и, n = 46) => String(s).slice(и, и + n).replace(/\n/g, '⏎');

function чемОтличается(a, b) {
  const иа = String(a).startsWith('ИСКЛ:'), иб = String(b).startsWith('ИСКЛ:');
  if (иа || иб) return `${иа ? a : 'отрисовано'} → ${иб ? b : 'отрисовано'}`;
  const та = ТЕКСТЫ(a), тб = ТЕКСТЫ(b);
  if (та.length !== тб.length) return `узлов текста ${та.length} → ${тб.length}`;
  const инт = та.map((x, i) => i).filter(i => та[i] !== тб[i]);
  if (инт.length) { const i = инт[0]; return `текст «${та[i]}» → «${тб[i]}»` + (инт.length > 1 ? ` (и ещё ${инт.length - 1})` : ''); }
  const ка = КЕГЛИ(a), кб = КЕГЛИ(b);
  if (ка.length !== кб.length) return `кеглей в разметке ${ка.length} → ${кб.length}`;
  const инк = ка.map((x, i) => i).filter(i => ка[i] !== кб[i]);
  if (инк.length) { const i = инк[0]; return `кегль ${ка[i]} → ${кб[i]}` + (инк.length > 1 ? ` (мест ${инк.length})` : ''); }
  let i = 0; while (i < a.length && i < b.length && a[i] === b[i]) i++;
  return `разметка с позиции ${i}: «${срез(a, i)}» → «${срез(b, i)}»`;
}

