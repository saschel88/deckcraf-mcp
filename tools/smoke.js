/* ══════ ЗАДАЧА 16: МЕРА ТЕКСТА ЗНАЕТ РЕГИСТР И МЕЖБУКВЕННЫЙ ЗАЗОР ══════
   До правки мера считала «длина × кегль × 0.55» и врала трижды: прописная
   шире строчной на пятую часть, семь стилей поднимают регистр ПОСЛЕ замера,
   а letter-spacing (1.4–2.4px в этих же семи) в меру не входил вовсе.
   Пробы написаны до правки и на нетронутом коде красные. */

const кеглиПо = (svg, начало) => {
  const из = [];
  for (const m of String(svg).matchAll(/<text([^>]*)>([^<]*)</g))
    if (m[2].toLowerCase().startsWith(начало.toLowerCase()))
      из.push(+(/font-size="([\d.]+)"/.exec(m[1]) || [])[1]);
  return из;
};

/* 1. Одна длина, разный регистр. Мера, считающая знаки, обязана дать
      прописным меньший кегль — они шире. Старая мера видела только длину
      и давала обеим строкам один кегль. Стиль без капса нарочно:
      проба меряет сам класс знака, а не подъём регистра. */
{
  const низ = 'а'.repeat(24), верх = 'А'.repeat(24);
  await вызов('start', { style: 'flat' });
  const кН = кеглиПо(JSON.parse((await вызов('draw', { id: 'kpi', data: { label: низ } })).текст).svg, низ.slice(0, 6))[0];
  const кВ = кеглиПо(JSON.parse((await вызов('draw', { id: 'kpi', data: { label: верх } })).текст).svg, верх.slice(0, 6))[0];
  проба('мера: прописные ужимаются сильнее строчных той же длины',
    кН != null && кВ != null && кВ < кН, `строчные ${кН}, прописные ${кВ}`);
}

