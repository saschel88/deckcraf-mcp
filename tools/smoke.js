/* ── Наряд 28, первая половина Д-3: образец m22 стоял зеркально ──
   Сама смысловая ошибка пробой не ловилась, пока порядок слотов нигде
   не был записан: разметка валидна, предупреждений нет, спорить не с чем.
   Теперь договор говорит, какой индекс куда идёт и что означают оси, —
   и ошибка стала выразимой. Проба ниже НЕ повторяет геометрию: место
   слота она берёт из договора, а канон Эйзенхауэра — единственное знание
   о мире, которое здесь и записывается:

     важно и срочно          → Сделать        слот [1]
     важно, НЕ срочно        → Спланировать   слот [0]
     НЕ важно, срочно        → Делегировать   слот [3]
     НЕ важно, НЕ срочно     → Убрать         слот [2]

   Владелец разрешил пересборку тринадцати пар m22 вариантом В:
   подписи и цвета переставляются вместе, места (xM, yM) не трогаются. */
{
  const спец = JSON.parse(readFileSync(new URL('../spec/elements.json', import.meta.url), 'utf8'))['элементы'];
  const порядок = спец.find(э => э.id === 'm22')['композиция']['порядок_слотов'];
  const местоСлота = и => порядок[String(и)].split(' ').reverse().join(' ');
  const канон = { 'Сделать': 1, 'Спланировать': 0, 'Делегировать': 3, 'Убрать': 2 };

  const образцовый = JSON.parse((await вызов('draw', { id: 'm22' })).текст)['svg'];
  const подписи = Object.keys(канон);
  const узлы = [...образцовый.matchAll(/<text\b[^>]*\bx="([-\d.]+)"[^>]*\by="([-\d.]+)"[^>]*>([^<]*)<\/text>/g)]
    .map(м => ({ x: +м[1], y: +м[2], т: м[3] }));
  const точки = подписи.map(п => узлы.find(у => у.т === п));
  проба('m22: все четыре образцовые подписи на месте в разметке', точки.every(Boolean),
    подписи.filter((п, i) => !точки[i]).join(', '));

  const cx = точки.filter(Boolean).reduce((с, т) => с + т.x, 0) / точки.filter(Boolean).length;
  const cy = точки.filter(Boolean).reduce((с, т) => с + т.y, 0) / точки.filter(Boolean).length;
  const место = т => `${т.y < cy ? 'верхний' : 'нижний'} ${т.x < cx ? 'левый' : 'правый'}`;
  const разбор = подписи.map((п, i) => точки[i]
    ? `${п}: ${место(точки[i])}, канон требует ${местоСлота(канон[п])}` : `${п}: нет`).join(' · ');
  проба('m22: образцовые квадранты Эйзенхауэра стоят по канону',
    точки.every(Boolean) && подписи.every((п, i) => место(точки[i]) === местоСлота(канон[п])), разбор);

  /* Договор объявляет доминантой квадрант «сделать» и — с круга правок
     наряда 28 — называет РОЛЬ, которой она выражена: m22.композиция.
     роли_цвета. Раньше здесь стояло зашитое `ST[к].pos`, то есть проба
     закрепляла как инвариант чтение, которого в договоре не было.
     Код-ревью это и поймало: токен, который НАЗЫВАЕТСЯ акцентным, —
     это ac, и лежит он на «Спланировать».

     Теперь ожидание целиком берётся из договора: какой слот несёт
     доминанту и каким токеном выражен каждый из четырёх. Ни одного
     цвета и ни одного имени токена в пробе не записано — разъехаться
     договор и код молча не могут.

     Проверяются ВСЕ ЧЕТЫРЕ слота и все тринадцать стилей: цвет квадранта
     задаётся поштучно, и правка в одном стиле прошла бы мимо пробы,
     смотрящей на один.

     Носителей цвета два, и выбирает между ними замер, а не список имён:
     где плашка есть — цвет на ней, где её нет (line и retro обходятся
     без подложек) — цвет несёт сама подпись.

     brutal исключается замером, а не по имени: у него все четыре токена
     #000000, стиль ахроматичен по своей цветовой модели, и доминанта
     в нём цветом невыразима. Условие проверяется числом различимых
     токенов, поэтому стиль, переставший быть ахроматичным, войдёт
     в проверку сам. */
  {
    const роли = спец.find(э => э.id === 'm22')['композиция']['роли_цвета'];
    const слоты = ['0', '1', '2', '3'];
    const токен = и => роли[и]['токен_в_коде'];
    const слотДоминанты = слоты.find(и => роли[и]['доминанта'] === true);
    проба('договор называет ровно один слот доминантным и даёт токен каждому',
      слотДоминанты !== undefined &&
      слоты.filter(и => роли[и]['доминанта'] === true).length === 1 &&
      слоты.every(и => typeof токен(и) === 'string'),
      JSON.stringify(роли));

    /* доминанта договора обязана стоять там же, где канон ставит «Сделать» */
    проба('доминантный слот — тот же, что канон отдаёт «Сделать»',
      Number(слотДоминанты) === канон['Сделать'],
      `договор: слот ${слотДоминанты}; канон «Сделать»: слот ${канон['Сделать']}`);

    const подписьВСтиле = (svg, п, s) => {
      const о = s.caps ? п.toUpperCase() : п;
      return [...svg.matchAll(/<text\b[^>]*\bx="([-\d.]+)"[^>]*\by="([-\d.]+)"[^>]*fill="([^"]+)"[^>]*>([^<]*)<\/text>/g)]
        .map(м => ({ x: +м[1], y: +м[2], ц: м[3], т: м[4] }))
        .find(у => { const т = у.т.endsWith('…') ? у.т.slice(0, -1) : у.т;
          return т.length >= 2 && о.startsWith(т); });
    };
    const цветПод = (svg, узел) => {
      const бл = [...svg.matchAll(/<rect x="([-\d.]+)" y="([-\d.]+)" width="([-\d.]+)" height="([-\d.]+)"[^>]*fill="([^"]+)"/g)]
        .map(м => ({ cx: +м[1] + +м[3] / 2, cy: +м[2] + +м[4] / 2, ц: м[5] }))
        .map(п => ({ ...п, d: Math.hypot(п.cx - узел.x, п.cy - узел.y) }))
        .sort((a, b) => a.d - b.d)[0];
      return (бл && бл.d < 12) ? бл.ц : узел.ц;
    };
    /* подпись, стоящая в слоте: канон говорит, какая именно */
    const подписьСлота = и => Object.keys(канон).find(п => канон[п] === Number(и));

    const цветные = [], разошлись = [], ахроматичные = [];
    for (const к of Object.keys(ST).filter(к => к !== 'iso')) {
      const s = ST[к], svg = ОТРИСОВКА.get('m22')(s);
      if (new Set(слоты.map(и => s[токен(и)])).size === 1) { ахроматичные.push(к); continue; }
      цветные.push(к);
      for (const и of слоты) {
        const узел = подписьВСтиле(svg, подписьСлота(и), s);
        if (!узел) { разошлись.push(`${к}/[${и}]: подпись не найдена`); continue; }
        const ц = цветПод(svg, узел);
        if (ц !== s[токен(и)])
          разошлись.push(`${к}/[${и}] «${подписьСлота(и)}»: ${ц} против ${роли[и]['роль']} ${s[токен(и)]}`);
      }
    }
    проба('цвет каждого квадранта — тот, что назван в договоре, во всех цветных стилях',
      разошлись.length === 0 && цветные.length >= 12,
      `цветных стилей ${цветные.length}, слотов на стиль ${слоты.length}, сверок ${цветные.length * слоты.length}; ` +
      `ахроматичные (доминанта невыразима): ${ахроматичные.join(', ') || 'нет'}` +
      (разошлись.length ? `; разошлись: ${разошлись.slice(0, 6).join(' · ')}` : ''));
  }

}


/* ── Круг правок наряда 28, Н1: один ключ — один договор во всех
   инструментах ──
   Код-ревью: `не_рекомендуется_в_стиле` отдавался тремя формами. catalog —
   строкой, и на годной паре ключа не было вовсе; find и describe — объектом
   {почему, draw, что_делать} и null. Клиент, научившийся на describe читать
   `.почему`, получал от catalog undefined, а проверка «ключ есть» на find
   была истинной для каждой годной пары.

   Обидно это тем, что Д-2 был ровно про то же: одно поле обязано отвечать
   на один вопрос. Починив расхождение ВНУТРИ describe, мы завели такое же
   МЕЖДУ инструментами — и не заметили, потому что пробы сличали наличие
   пометки, а не её форму. Проба ниже сличает именно форму, и сразу у всех
   троих: разъехаться порознь они больше не смогут. */
{
  await вызов('start', { style: 'clay' });
  const форма = з => з === undefined ? 'ключа нет'
    : з === null ? 'null'
    : (typeof з === 'object' && !Array.isArray(з)) ? 'объект' : typeof з;

  const каталог = JSON.parse((await вызов('catalog', { category: 'Диаграммы и данные' })).текст)
    ['разделы'].flatMap(р => р['элементы']);
  const кат = ид => каталог.find(э => э['id'] === ид);
  const опис = async ид => JSON.parse((await вызов('describe', { id: ид })).текст);
  const кандидаты = JSON.parse((await вызов('find', { query: 'диаграмма рассеяния' })).текст)['кандидаты'] || [];
  const поиск = ид => кандидаты.find(э => э['id'] === ид);

  /* негодная пара: scat × clay — «пластилину нужна физическая форма» */
  const негодные = [['catalog', кат('scat')], ['find', поиск('scat')], ['describe', await опис('scat')]]
    .map(([имя, о]) => [имя, о && о['не_рекомендуется_в_стиле']]);
  проба('негодная пара: поле одной формы во всех трёх инструментах',
    негодные.every(([, з]) => форма(з) === 'объект'),
    негодные.map(([имя, з]) => `${имя}: ${форма(з)}`).join(' · '));
  проба('негодная пара: причина читается одинаково во всех трёх',
    негодные.every(([, з]) => з && typeof з['почему'] === 'string') &&
    new Set(негодные.map(([, з]) => з && з['почему'])).size === 1,
    негодные.map(([имя, з]) => `${имя}: ${з && з['почему']}`).join(' · '));

  /* годная пара: kpi × clay. Ключ обязан БЫТЬ и обязан быть null —
     «ключа нет» и null для клиента разные ответы. */
  const годные = [['catalog', кат('kpi')], ['describe', await опис('kpi')]]
    .map(([имя, о]) => [имя, о && ('не_рекомендуется_в_стиле' in о ? о['не_рекомендуется_в_стиле'] : undefined)]);
  const годныйИзПоиска = кандидаты.find(э => э['id'] !== 'scat');
  if (годныйИзПоиска) годные.push(['find',
    'не_рекомендуется_в_стиле' in годныйИзПоиска ? годныйИзПоиска['не_рекомендуется_в_стиле'] : undefined]);
  проба('годная пара: поле есть и равно null во всех инструментах',
    годные.length >= 3 && годные.every(([, з]) => форма(з) === 'null'),
    годные.map(([имя, з]) => `${имя}: ${форма(з)}`).join(' · '));

  await вызов('start', { style: 'flat' });
}


/* ── Наряд 30: штатное место протокола вместо самодельного ──
   Разведка (задача 27): в спецификации MCP от 2025-06-18 у результата
   инструмента есть `structuredContent` и `outputSchema`, и клиент обязан
   сверять результат по схеме. Мы же кладём весь машиночитаемый ответ одним
   блоком `type: 'text'` — то есть придумали своё поле там, где в протоколе
   уже есть штатное: src/index.js, `const ответ = о => ({ content: [{ type:
   'text', text: JSON.stringify(о, null, 2) }] })`.

   ПЕРЕВОД ИДЁТ ДУБЛИРОВАНИЕМ, А НЕ ПЕРЕНОСОМ. Известен случай, когда клиент
   показывал только structuredContent и терял content
   (github.com/anthropics/claude-code/issues/15412). Поэтому проба сторожит
   обе стороны разом: structuredContent обязан появиться, content обязан
   остаться непустым и по-прежнему нести JSON, и оба обязаны нести ОДИН И ТОТ
   ЖЕ объект. Сличается разбором, а не строкой: строковое сравнение зависит от
   порядка ключей и отступов, а нам важно, чтобы вторая сторона не оказалась
   переписанной от руки.

   ПЕРЕБОР ИДЁТ ПО СПИСКУ ШЕСТИ, А НЕ ПО ТОМУ, ЧТО ОТДАЛ listTools. Ворота
   «есть ли ключ» этот проект уже проходил: перебор по наличию молча
   выкидывал поля из проверки и печатал «нарушений 0». Инструмент без схемы
   обязан РОНЯТЬ пробу, а не выпадать из неё. И каждое утверждение
   проверяется сразу у всех шести одним счётом — наряд 28 показал, как одно
   понятие разъезжается в три формы, когда каждый инструмент проверяется
   отдельным утверждением, и все три утверждения по отдельности проходят.

   Схемы объявляются РУССКИМИ ключами, и это не оплошность. Шаблон
   ^[a-zA-Z0-9_.-]{1,64}$, на котором обжёгся inputSchema (см. host-check.js),
   приходит от Anthropic API, а в определении инструмента Messages API есть
   только name, description и input_schema — outputSchema туда не едет вовсе.
   Её читает MCP-клиент, а он ключи не ограничивает: ajv из того же SDK
   проверяет «стиль» наравне с латиницей. Переименовывать ключи ответа
   нельзя — они русские по ТЗ и лежат под эталоном. */
{
  const ШЕСТЬ = ['styles', 'start', 'catalog', 'find', 'describe', 'draw'];
  /* Порядок не случаен: find, describe и draw до start отказывают, поэтому
     start идёт вторым и фиксирует стиль на весь блок. Проба, утверждающая
     невозможное, в этом проекте уже была — стиль сессии не снимается. */
  const ВЫЗОВЫ = {
    styles: {}, start: { style: 'flat' }, catalog: {},
    find: { query: 'воронка' }, describe: { id: 'kpi' }, draw: { id: 'bars' }
  };

  const схемы = new Map(tools.map(т => [т.name, т.outputSchema]));
  const проверятель = new AjvJsonSchemaValidator();

  /* callTool у SDK-клиента сам роняет исключение, если outputSchema объявлена,
     а structuredContent не пришёл, — то есть ровно на полусделанной правке.
     Ловим: проба обязана напечатать числа, а не оборвать прогон стеком. */
  const сырой = async (имя, арг) => {
    try { return { ответ: await клиент.callTool({ name: имя, arguments: арг }) }; }
    catch (e) { return { отвергнут: e?.message || String(e) }; }
  };

  const кратко = з => { const с = JSON.stringify(з) ?? String(з); return с.length > 40 ? с.slice(0, 40) + '…' : с; };
  /* Не «равны/не равны», а адрес первого расхождения: молчаливое «false»
     на объекте в тысячу ключей чинить не по чему. */
  const перваяРазница = (a, b, путь = '') => {
    const адрес = путь || '·';
    if (a === b) return null;
    const оба = a && b && typeof a === 'object' && typeof b === 'object';
    if (!оба) return `${адрес}: ${кратко(a)} против ${кратко(b)}`;
    if (Array.isArray(a) !== Array.isArray(b)) return `${адрес}: массив против объекта`;
    if (Array.isArray(a)) {
      if (a.length !== b.length) return `${адрес}: длина ${a.length} против ${b.length}`;
      for (let i = 0; i < a.length; i++) { const р = перваяРазница(a[i], b[i], `${путь}[${i}]`); if (р) return р; }
      return null;
    }
    const ка = Object.keys(a), кб = Object.keys(b);
    const слева = ка.filter(к => !кб.includes(к)), справа = кб.filter(к => !ка.includes(к));
    if (слева.length || справа.length)
      return `${адрес}: только в structuredContent — ${слева.join(', ') || 'нет'}; только в content — ${справа.join(', ') || 'нет'}`;
    for (const к of ка) { const р = перваяРазница(a[к], b[к], `${путь}.${к}`); if (р) return р; }
    return null;
  };

  const снимки = new Map();
  for (const имя of ШЕСТЬ) снимки.set(имя, await сырой(имя, ВЫЗОВЫ[имя]));

  const данные = new Map(ШЕСТЬ.map(имя => {
    const с = снимки.get(имя);
    if (с.отвергнут) return [имя, { беда: `клиент отверг ответ — ${с.отвергнут}` }];
    const о = с.ответ;
    const блоки = Array.isArray(о.content) ? о.content : [];
    let изТекста, текстСломан = null;
    if (блоки[0]?.type === 'text')
      try { изТекста = JSON.parse(блоки[0].text); } catch (e) { текстСломан = e.message; }
    return [имя, { о, блоки, изТекста, текстСломан, sc: о.structuredContent }];
  }));

  /* 1. Схема объявлена. Перебор по ШЕСТЬ: инструмента, которого нет в
     listTools вовсе, это тоже касается. */
  const нетСхемы = ШЕСТЬ.filter(имя => {
    const с = схемы.get(имя);
    return !(с && typeof с === 'object' && !Array.isArray(с) && с.type === 'object');
  });
  проба('outputSchema объявлена у всех шести инструментов',
    нетСхемы.length === 0,
    `объявлена у ${ШЕСТЬ.length - нетСхемы.length} из ${ШЕСТЬ.length}` +
    (нетСхемы.length ? `; без схемы: ${нетСхемы.join(', ')}` : ''));

  /* 2. Схема — не заглушка. `{type:'object'}` без properties и без required
     пропускает даже {}: объявлена, а не говорит ничего. */
  const заглушки = [];
  for (const имя of ШЕСТЬ) {
    const с = схемы.get(имя);
    if (!с || typeof с !== 'object') { заглушки.push(`${имя}: схемы нет`); continue; }
    const свойства = Object.keys(с.properties || {});
    const обязательные = Array.isArray(с.required) ? с.required : [];
    const мимо = обязательные.filter(к => !свойства.includes(к));
    if (!свойства.length) заглушки.push(`${имя}: properties пуст`);
    else if (!обязательные.length) заглушки.push(`${имя}: required пуст — схему проходит даже {}`);
    else if (мимо.length) заглушки.push(`${имя}: required называет неописанное — ${мимо.join(', ')}`);
  }
  проба('схема не заглушка: называет поля и требует хотя бы одно',
    заглушки.length === 0,
    заглушки.length ? `${заглушки.length} из ${ШЕСТЬ.length}: ${заглушки.join(' · ')}`
      : ШЕСТЬ.map(имя => `${имя}: полей ${Object.keys(схемы.get(имя).properties).length}, обязательных ${схемы.get(имя).required.length}`).join(' · '));

  /* 3. structuredContent пришёл, и это объект: массив и строка протоколом
     не предусмотрены. */
  const безSC = ШЕСТЬ.filter(имя => {
    const д = данные.get(имя);
    return д.беда || !(д.sc && typeof д.sc === 'object' && !Array.isArray(д.sc));
  });
  проба('structuredContent пришёл объектом у всех шести',
    безSC.length === 0,
    `есть у ${ШЕСТЬ.length - безSC.length} из ${ШЕСТЬ.length}` +
    (безSC.length ? `; нет у: ${безSC.join(', ')}` : ''));

  /* 4. content на месте — дублирование, а не перенос. Зелено и сейчас:
     это сторож против правки, которая опустошит content. */
  const сломанContent = [];
  for (const имя of ШЕСТЬ) {
    const д = данные.get(имя);
    if (д.беда) { сломанContent.push(`${имя}: ${д.беда}`); continue; }
    if (!д.блоки.length) сломанContent.push(`${имя}: content опустел`);
    else if (д.блоки[0].type !== 'text') сломанContent.push(`${имя}: первый блок «${д.блоки[0].type}»`);
    else if (!д.блоки[0].text) сломанContent.push(`${имя}: текст пуст`);
    else if (д.текстСломан) сломанContent.push(`${имя}: текст не разбирается — ${д.текстСломан}`);
  }
  проба('content остался на месте и по-прежнему несёт JSON (дублирование, а не перенос)',
    сломанContent.length === 0,
    сломанContent.length ? `${сломанContent.length} из ${ШЕСТЬ.length}: ${сломанContent.join(' · ')}`
      : ШЕСТЬ.map(имя => `${имя}: ${данные.get(имя).блоки[0].text.length} знаков`).join(' · '));

  /* 5. Обе стороны несут один объект. Сличение разбором. */
  const разошлись = [];
  for (const имя of ШЕСТЬ) {
    const д = данные.get(имя);
    if (д.беда) { разошлись.push(`${имя}: ${д.беда}`); continue; }
    if (д.sc === undefined) { разошлись.push(`${имя}: structuredContent не пришёл`); continue; }
    if (д.изТекста === undefined) { разошлись.push(`${имя}: content[0].text не разобрался`); continue; }
    const р = перваяРазница(д.sc, д.изТекста);
    if (р) разошлись.push(`${имя} → ${р}`);
  }
  проба('structuredContent совпадает с разобранным content[0].text у всех шести',
    разошлись.length === 0,
    разошлись.length ? `расхождений ${разошлись.length} из ${ШЕСТЬ.length}: ${разошлись.slice(0, 3).join(' · ')}`
      : `сличено пар ${ШЕСТЬ.length}, ключей верхнего уровня ${ШЕСТЬ.reduce((с, имя) => с + Object.keys(данные.get(имя).sc).length, 0)}`);

  /* 6. Ответ проходит по СВОЕЙ схеме — тем же ajv, каким его проверит клиент.
     Схемы нет — проверять не по чему, и это сбой, а не пропуск. */
  const неПрошли = [];
  for (const имя of ШЕСТЬ) {
    const с = схемы.get(имя), д = данные.get(имя);
    if (!с) { неПрошли.push(`${имя}: схемы нет — проверять не по чему`); continue; }
    if (д.беда) { неПрошли.push(`${имя}: ${д.беда}`); continue; }
    if (д.sc === undefined) { неПрошли.push(`${имя}: structuredContent не пришёл`); continue; }
    try {
      const вердикт = проверятель.getValidator(с)(д.sc);
      if (!вердикт.valid) неПрошли.push(`${имя}: ${вердикт.errorMessage}`);
    } catch (e) { неПрошли.push(`${имя}: схема не компилируется — ${e.message}`); }
  }
  проба('structuredContent проходит по объявленной outputSchema у всех шести',
    неПрошли.length === 0,
    неПрошли.length ? `не прошли ${неПрошли.length} из ${ШЕСТЬ.length}: ${неПрошли.slice(0, 3).join(' · ')}`
      : `проверено ${ШЕСТЬ.length} из ${ШЕСТЬ.length}`);

  /* 7. Приговор самого клиента. Сейчас он молчит — схем нет, проверять
     нечего, — и пояснение это прямо печатает, чтобы зелёное не сошло за
     доказательство. После правки это единственная проба, где судит не наш
     разбор, а SDK-клиент своими правилами. */
  const отвергнутые = ШЕСТЬ.filter(имя => снимки.get(имя).отвергнут);
  проба('ни один из шести ответов не отвергнут самим MCP-клиентом',
    отвергнутые.length === 0,
    отвергнутые.length ? отвергнутые.map(имя => `${имя}: ${снимки.get(имя).отвергнут}`).join(' · ')
      : `сверку ведёт клиент SDK; схем объявлено ${ШЕСТЬ.filter(имя => схемы.get(имя)).length} из ${ШЕСТЬ.length}`);

  /* 8. Отказы. Отказ — не результат, и под схему результата он не подходит:
     describe отказа везёт человеческий текст, а не «композицию» и «данные».
     Спецификация и клиент SDK сходятся: при isError структурированная часть
     не требуется и не проверяется. Значит верно так — отказ остаётся текстом,
     structuredContent при нём не появляется вовсе. Проба сторожит правку,
     которая приклеит structuredContent ко всем ответам подряд: тогда каждый
     отказ перестал бы проходить по схеме, и клиент рушил бы вызов вместо
     того, чтобы показать причину. Зелена и сейчас — сторож, а не находка. */
  const ОТКАЗЫ = [['start', { style: 'нетакого' }], ['catalog', { category: 'нетакого' }],
                  ['describe', { id: 'нетакого' }], ['draw', { id: 'нетакого' }]];
  const плохиеОтказы = [];
  for (const [имя, арг] of ОТКАЗЫ) {
    const с = await сырой(имя, арг);
    if (с.отвергнут) { плохиеОтказы.push(`${имя}: клиент отверг отказ — ${с.отвергнут}`); continue; }
    const о = с.ответ;
    if (о.isError !== true) плохиеОтказы.push(`${имя}: isError не выставлен`);
    else if (о.structuredContent !== undefined) плохиеОтказы.push(`${имя}: при isError пришёл structuredContent`);
    else if (!(о.content?.[0]?.type === 'text' && о.content[0].text.length > 10))
      плохиеОтказы.push(`${имя}: причина отказа не читается текстом`);
  }
  проба('отказ остаётся текстом: isError, без structuredContent, причина читается',
    плохиеОтказы.length === 0,
    плохиеОтказы.length ? `${плохиеОтказы.length} из ${ОТКАЗЫ.length}: ${плохиеОтказы.join(' · ')}`
      : `проверено отказов ${ОТКАЗЫ.length} из ${ОТКАЗЫ.length}`);

  await вызов('start', { style: 'flat' });
}

await клиент.close();
const сбоев = итог.filter(x => !x).length;
console.log(`\nпроверок ${итог.length}, сбоев ${сбоев}`);
