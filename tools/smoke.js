/* ══════ ЗАДАЧА 16: МЕРА ТЕКСТА ЗНАЕТ РЕГИСТР И МЕЖБУКВЕННЫЙ ЗАЗОР ══════
   До правки мера считала «длина × кегль × 0.55» и врала трижды: прописная
   шире строчной на пятую часть, семь стилей поднимают регистр ПОСЛЕ замера,
   а letter-spacing (1.4–2.4px в этих же семи) в меру не входил вовсе.
   Пробы написаны до правки и на нетронутом коде красные. */

const кеглиПо = (svg, начало) => {
  const из = [];
  for (const m of String(svg).matchAll(/<text([^>]*)>([^<]*)</g))
    if (m[2].toLowerCase().startsWith(начало.toLowerCase()))
      из.push(+(/font-size="([\d.]+)"/.exec(m[1]) || [])[1]);
  return из;
};

