/* Прогон сервера настоящим MCP-клиентом по stdio: шесть инструментов
   и правило «пока стиль не выбран — ошибка». */

import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const клиент = new Client({ name: 'smoke', version: '1.0.0' });
await клиент.connect(new StdioClientTransport({
  command: process.execPath,
  args: [new URL('../src/index.js', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')],
  stderr: 'pipe'
}));

const вызов = async (имя, арг = {}) => {
  const р = await клиент.callTool({ name: имя, arguments: арг });
  return { ошибка: !!р.isError, текст: р.content[0].text };
};
const итог = [];
const проба = (что, условие, пояснение = '') => {
  итог.push(условие);
  console.log(`  ${условие ? 'ок  ' : 'СБОЙ'}  ${что}${пояснение ? ' — ' + пояснение : ''}`);
};

const { tools } = await клиент.listTools();
проба('инструментов шесть', tools.length === 6, tools.map(t => t.name).join(', '));
проба('имена проходят шаблон API', tools.every(t => /^[a-zA-Z0-9_-]{1,64}$/.test(t.name)));

/* catalog намеренно живёт до выбора стиля: это первый вопрос человека,
   а не следствие уже принятого решения. */
const каталог = JSON.parse((await вызов('catalog')).текст);
проба('catalog работает без start', каталог['всего'] === 52, `разделов ${каталог['разделы'].length}`);
проба('catalog без стиля не помечает доступность',
  каталог['разделы'].every(р => р['элементы'].every(э => !('доступен_в_стиле' in э))));
проба('catalog считает элементы с данными', каталог['принимают_данные'] === 45);
проба('catalog фильтрует по разделу',
  JSON.parse((await вызов('catalog', { category: 'Шаги и процессы' })).текст)['разделы'].length === 1);
проба('catalog отвергает несуществующий раздел', (await вызов('catalog', { category: 'нетакого' })).ошибка);

for (const имя of ['find', 'describe', 'draw']) {
  const р = await вызов(имя, имя === 'find' ? { query: 'воронка' } : { id: 'kpi' });
  проба(`${имя} без start отказывает`, р.ошибка && /Стиль не выбран/.test(р.текст));
}

const стили = JSON.parse((await вызов('styles')).текст);
проба('styles отдаёт 13 стилей', стили['стили'].length === 13);
проба('у каждого стиля есть требования к фону', стили['стили'].every(с => с['фон'] && с['фон']['требуется']));

const старт = JSON.parse((await вызов('start', { style: 'flat' })).текст);
проба('start фиксирует стиль', старт['стиль'] === 'flat' && старт['зафиксирован'] === true);
проба('start отдаёт спецификацию и фон', !!старт['спецификация']['геометрия'] && !!старт['фон']['требуется']);
проба('start отвергает несуществующий стиль', (await вызов('start', { style: 'нетакого' })).ошибка);

const послеСтарта = JSON.parse((await вызов('catalog')).текст);
проба('catalog после start помечает доступность',
  послеСтарта['стиль'] === 'flat' &&
  послеСтарта['разделы'].every(р => р['элементы'].every(э => typeof э['доступен_в_стиле'] === 'boolean')));
проба('русский синоним параметра принят',
  JSON.parse((await вызов('start', { 'стиль': 'flat' })).текст)['стиль'] === 'flat');

const поиск = JSON.parse((await вызов('find', { query: 'показать как отсеиваются кандидаты по этапам' })).текст);
проба('find возвращает 1–3 кандидата', поиск['кандидаты'].length >= 1 && поиск['кандидаты'].length <= 3,
  поиск['кандидаты'].map(к => к.id).join(', '));
проба('find всегда отдаёт «не применять»', поиск['кандидаты'].every(к => к['не_применять']));

const опис = JSON.parse((await вызов('describe', { id: 'kpi' })).текст);
проба('describe отдаёт композицию и договор', !!опис['композиция'] && !!опис['данные']);
проба('describe отдаёт требования к фону стиля', !!опис['фон']['требуется']);

const комп = JSON.stringify(опис['композиция']);
проба('композиция задана числами, а не словами', /\d/.test(комп), комп.slice(0, 80));

/* все 52, а не только kpi — числа снимались измерением по каждому элементу отдельно */
const всеИды = каталог['разделы'].flatMap(р => р['элементы']).map(э => э['id']);
const безЧисел = [];
for (const ид of всеИды) {
  const о = JSON.parse((await вызов('describe', { id: ид })).текст);
  if (о['композиция'] && !/\d/.test(JSON.stringify(о['композиция']))) безЧисел.push(ид);
}
проба('композиция с числами у всех элементов', безЧисел.length === 0, безЧисел.join(', '));

/* пример_данных — образец, вынесенный из тела функции отрисовки, а не переписанный
   от руки: доказательство — отрисовка этим образцом побайтово совпадает с отрисовкой
   без данных вовсе (обе идут через один и тот же fallback-путь ряды()/строка()) */
const описBars = JSON.parse((await вызов('describe', { id: 'bars' })).текст);
проба('describe отдаёт пример данных', !!описBars['пример_данных'],
  JSON.stringify(описBars['пример_данных'] || null).slice(0, 80));

/* Проверка не только на bars: у любого элемента с пример_данными отрисовка этим
   образцом обязана побайтово совпасть с отрисовкой без данных вовсе — иначе
   пример переписан от руки, а не перенесён из тела функции. timeline — известное,
   осознанно не исправленное исключение (см. описание в самом describe у timeline,
   поле пример_данных_оговорка): доля прогресса без данных зашита на глаз (.66),
   а при явных points (даже этим самым массивом) считается по формуле (2/3).
   Приводить их друг к другу нельзя — это изменит отрисовку образца, которая
   лежит под эталоном 676 пар. Список ниже обязан падать в обе стороны: если
   расхождение появится у элемента, которого тут нет, и если расхождение у
   timeline вдруг исчезнет — устаревшее исключение врёт про состояние кода
   не хуже отсутствующего. */
const ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ = { timeline: 'доля прогресса: .66 зашито против 2/3 вычисленного' };

const сПримером = [];
for (const ид of всеИды) {
  const о = JSON.parse((await вызов('describe', { id: ид })).текст);
  if (о['пример_данных']) сПримером.push([ид, о['пример_данных']]);
}
проба('пример_данных есть у всех элементов, принимающих данные',
  сПримером.length === каталог['принимают_данные'], `${сПримером.length} из ${каталог['принимают_данные']}`);

const расхожденияНайдены = [];
for (const [ид, пример] of сПримером) {
  const сОбразцом = JSON.parse((await вызов('draw', { id: ид, data: пример })).текст)['svg'];
  const безДанных = JSON.parse((await вызов('draw', { id: ид })).текст)['svg'];
  if (сОбразцом !== безДанных) расхожденияНайдены.push(ид);
}
const непойманные = расхожденияНайдены.filter(ид => !(ид in ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ));
проба(`пример данных совпадает с образцовой отрисовкой у всех ${сПримером.length} элементов, кроме известных исключений`,
  непойманные.length === 0, непойманные.join(', '));

const устаревшиеИсключения = Object.keys(ИЗВЕСТНЫЕ_РАСХОЖДЕНИЯ).filter(ид => !расхожденияНайдены.includes(ид));
проба('известные исключения по-прежнему воспроизводятся (иначе список устарел)',
  устаревшиеИсключения.length === 0, устаревшиеИсключения.join(', '));

const рис = JSON.parse((await вызов('draw', { id: 'kpi' })).текст);
проба('draw отдаёт валидный SVG', /^<svg[^>]*>[\s\S]*<\/svg>$/.test(рис['svg']));
проба('холст 300 по ширине', рис['холст']['ширина'] === 300, JSON.stringify(рис['холст']));
проба('предупреждения — массив', Array.isArray(рис['предупреждения']));

/* Элемент, уже принимающий данные: подписи должны дойти до разметки,
   а холст — вырасти под пять рядов вместо трёх */
const сдан = JSON.parse((await вызов('draw', {
  id: 'bars',
  'данные': {
    title: 'НАО Госкорпорация',
    rows: [{ label: 'Затраты на персонал', v: 40 }, { label: 'Капитальные вложения', v: 92 },
           { label: 'Аренда', v: 12 }, { label: 'Прочее', v: 65 }, { label: 'Налоги', v: 33 }]
  }
})).текст);
проба('данные доходят до разметки', /Затраты на персонал/.test(сдан['svg']) && /40%/.test(сдан['svg']));
проба('данные применились без оговорки', !сдан['предупреждения'].some(п => /данные пока не принимает/.test(п)));
проба('холст вырос под лишние ряды', сдан['холст']['высота'] > 190, `высота ${сдан['холст']['высота']}`);
проба('сервер сообщил о росте холста', сдан['предупреждения'].some(п => /холст вырос/.test(п)));

/* Элемент, ещё не переведённый на данные, обязан сказать об этом честно */
const необучен = JSON.parse((await вызов('draw', { id: 'kpi', 'данные': { label: 'Выручка', value: '₸2.4B' } })).текст);
проба('непереведённый элемент честно предупреждает',
  необучен['предупреждения'].some(п => /данные пока не принимает/.test(п)));

const кривые = JSON.parse((await вызов('draw', { id: 'bars', data: { rows: 'не массив', лишнее: 1 } })).текст);
проба('несоответствие договору попадает в предупреждения',
  кривые['предупреждения'].some(п => /ждёт массив/.test(п)) &&
  кривые['предупреждения'].some(п => /не предусмотрено/.test(п)));
проба('кривые данные не рушат отрисовку', /^<svg/.test(кривые['svg']));

/* Живая проба четырьмя параллельными агентами показала: сервер один на всех,
   ключ сессии у stdio постоянный, и соседний потребитель переписывает стиль.
   Отсюда три требования — ответ обязан называть стиль, стиль можно задать
   поштучно, а расхождение с сессией обязано быть видно. */
проба('draw называет стиль, которым рисовал', рис['стиль'] === 'flat' && рис['стиль_взят'] === 'из состояния сессии');

const поштучно = JSON.parse((await вызов('draw', { id: 'kpi', style: 'shadow' })).текст);
проба('style в запросе перебивает стиль сессии',
  поштучно['стиль'] === 'shadow' && /feDropShadow/.test(поштучно['svg']));
проба('поштучный стиль не меняет выбор сессии',
  JSON.parse((await вызов('draw', { id: 'kpi' })).текст)['стиль'] === 'flat');
проба('смешение стилей попадает в предупреждения',
  поштучно['предупреждения'].some(п => /стили смешивать нельзя/.test(п)));
проба('draw отвергает несуществующий style', (await вызов('draw', { id: 'kpi', style: 'нетакого' })).ошибка);

/* Обе потери данных были немыми: лишние ряды отбрасывались, подписи резались */
const лишние = JSON.parse((await вызов('draw', {
  id: 'bars', data: { title: 'Т', rows: [1,2,3,4,5,6,7,8].map(i => ({ label: 'Строка ' + i, v: 10 * i })) }
})).текст);
проба('превышение договорного количества замечено',
  лишние['предупреждения'].some(п => /передано 8, договор требует 2–5/.test(п)));

const обрезка = JSON.parse((await вызов('draw', {
  id: 'funnel', style: 'shadow',
  data: { title: 'Продажи', levels: [
    { label: 'Первый контакт', value: '4 200', k: 1 },
    { label: 'Квалификация лида', value: '1 850', k: 0.6 },
    { label: 'Сделка', value: '210', k: 0.38 }] }
})).текст);
проба('обрезанная подпись попадает в предупреждения',
  обрезка['предупреждения'].some(п => /обрезаны/.test(п)),
  обрезка['предупреждения'].find(п => /обрезаны/.test(п)) || 'не сообщил');
проба('образцовая отрисовка обрезкой не считается',
  !JSON.parse((await вызов('draw', { id: 'funnel' })).текст)['предупреждения'].some(п => /обрезаны/.test(п)));

проба('draw отвергает несуществующий id', (await вызов('draw', { id: 'нетакого' })).ошибка);

/* retro/kpi рисовал дельту зашитым '+23%' вместо переданного label —
   выдуманное число противоположного знака вместо честной подписи */
const ретро = JSON.parse((await вызов('draw',
  { id: 'kpi', style: 'retro', data: { label: 'Затраты', value: '12.4B', delta: '▼ 41% г/г' } })).текст);
проба('дельта доходит до разметки в retro', /41%/.test(ретро['svg']),
  (ретро['svg'].match(/>[^<>]*%[^<>]*</g) || []).join(' '));

await клиент.close();
const сбоев = итог.filter(x => !x).length;
console.log(`\nпроверок ${итог.length}, сбоев ${сбоев}`);
process.exit(сбоев ? 1 : 0);
