const СТИЛИ = Object.keys(ST).filter(k => k !== 'iso');
let всего = 0, применились = 0, потеряно = 0, выросли = 0;
const счёт = {}, прирост = [];
const беды = [];

for (const [ид, данные] of Object.entries(Д)) {
  const э = ЭЛ.get(ид);
  if (!э) { беды.push(`${ид}: нет такого элемента`); continue; }
  for (const стиль of СТИЛИ) {
    всего++;
    const s = ST[стиль];
    let свой, образец;
    try { образец = э.fn(s); свой = э.fn(s, данные); }
    catch (e) { беды.push(`${стиль}/${ид}: ИСКЛЮЧЕНИЕ ${e.message}`); continue; }
    if (свой === образец) { беды.push(`${стиль}/${ид}: данные не применились`); continue; }
    применились++;

    /* Каждая переданная строка обязана оставить след: целиком либо усечённой.
       Пропала совсем — значит подстановка промахнулась мимо поля */
    const тексты = [...свой.matchAll(/<text[^>]*>([^<]*)<\/text>/g)].map(m => m[1]);
    const ожидаем = [];
    const собрать = з => {
      if (typeof з === 'string' && з.length > 2) ожидаем.push(з);
      else if (Array.isArray(з)) з.forEach(собрать);
      else if (з && typeof з === 'object') Object.values(з).forEach(собрать);
    };
    собрать(данные);
    /* Часть подписей элемент намеренно не прогоняет через t(): у стилей
       с caps регистр им не меняется. Поэтому годится любая из двух форм.
       Обрезка бывает двух видов: с многоточием (обычный ужать()) и без —
       heat.rows режет без точки нарочно, чтобы не выдумывать несуществующий
       смысл на тесном поле (наряд 14, шаг 5). Второй вид узнаём как
       нетривиальный префикс без многоточия на конце */
    const скрыто = НЕВИДИМО[ид] ? НЕВИДИМО[ид](данные, стиль) : [];
    for (const ж of ожидаем.filter(з => !скрыто.includes(з))) {
      const формы = [ж, ж.toUpperCase()];
      const есть = тексты.some(т => формы.includes(т) ||
        (т.endsWith('…') && формы.some(ф => ф.startsWith(т.slice(0, -1)))) ||
        (т.length >= 2 && !т.endsWith('…') && формы.some(ф => ф.startsWith(т) && ф.length > т.length)));
      if (!есть) { потеряно++; беды.push(`${стиль}/${ид}: «${ж}» не найдено в разметке`); }
    }
    if (холст(свой).высота > 190) выросли++;

    /* Шесть проверок на своих данных против них же на образце: интересен не
       общий счёт, а прирост. Он и означает, что элемент сломался под текстом */
    const было = проверить(образец, s).length, стало = проверить(свой, s);
    for (const з of стало) {
      счёт[з.проверка] = (счёт[з.проверка] || 0) + 1;
      if (з.проверка === 'разметка') беды.push(`${стиль}/${ид}: ${з.сообщение}`);
    }
    if (стало.length > было) прирост.push(`${стиль}/${ид}: ${было} → ${стало.length}  (${стало.slice(0, 1).map(з => з.сообщение)})`);
  }
}

