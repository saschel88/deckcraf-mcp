/* ── Что и как разбирается в договоре ──
   Разбор строгий и заякоренный: «до N знаков» с НАЧАЛА строки, а не первое
   число где угодно. Иначе «13» из хвоста «в самом тесном из 13 стилей» сошло
   бы за предел — и это не выдумка: ровно так сверитьДанные мягким /(\d+)/
   вытаскивала из «длины» vec.clusters число 35 (предел самого широкого
   из трёх скоплений) и мерила им все три при настоящих 12.

   У массива форм две, и выбирает между ними не список имён, а сам замер:
     «до N знаков на строку …»        — предел от числа строк не зависит;
     «строк → знаков: 1 → 46, 2 → 21…» — зависит, ширина слота делится
                                          на число строк.
   Обе разбираются здесь, обе сличаются ЧИСЛОМ. Сколько полей какой формы —
   сторожится отдельно: молчаливый переход одиннадцати полей на таблицу
   (или двух на одно число) пробу уронит. */
const разборДлины = сырое => {
  const с = String(сырое || '');
  const одно = /^до (\d+) знак/.exec(с);
  if (одно) return { вид: 'число', число: +одно[1] };
  const тб = /^строк → знаков: ([^—]+)—/.exec(с);
  if (тб) {
    const пары = [...тб[1].matchAll(/(\d+) → (\d+)/g)].map(m => [+m[1], +m[2]]);
    if (пары.length) return { вид: 'таблица', таблица: new Map(пары) };
  }
  /* Третья форма, и её тоже выбирает замер: поле, которое не ужимается
     вовсе. У arrows.steps.n номер рисуется как передан — обрезки не бывает
     ни при какой длине, и «до N знаков» было бы враньём наоборот. */
  if (/^обрезкой не ограничена/.test(с)) return { вид: 'не ограничено' };
  return null;
};

/* Законные числа строк — из «количества». Разбор СВОЙ и нарочно строгий:
   у сервера он мягче (последней веткой берёт любое число), и брать его сюда
   значило бы сделать пробу зелёной ровно там, где сервер ошибётся. Расхождение
   двух разборов проба поймает сама: у полей-таблиц ключи договорной таблицы
   обязаны совпасть с этим списком до числа. */
const числаСтрок = количество => {
  const с = String(количество || '').trim();
  let мин = null, макс = null;
  let m;
  if ((m = /^ровно (\d+)$/.exec(с))) { мин = макс = +m[1]; }
  else if ((m = /^(\d+)$/.exec(с))) { мин = макс = +m[1]; }
  else if ((m = /^(\d+)[–—-](\d+)$/.exec(с))) { мин = +m[1]; макс = +m[2]; }
  else if ((m = /^до (\d+)$/.exec(с))) { мин = 1; макс = +m[1]; }
  if (мин === null || мин < 1 || макс < мин) return null;
  const из = [];
  for (let n = мин; n <= макс; n++) из.push(n);
  return из;
};

