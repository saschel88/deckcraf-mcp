const годен = (ид, ст) => (ALLOW[ид] || СТИЛИ).includes(ст);

/* ── наборы данных ──
   Тот же приём, что в tools/diff-run.js: договорные данные вынимаются
   из исходника tools/data-check.js, где они и живут. Не вынулись — прогон
   падает ГРОМКО, а не тихо теряет покрытие. */
function договорные() {
  const т = readFileSync(путь('tools/data-check.js'), 'utf8');
  const н = т.indexOf('const Д = {');
  const к = н < 0 ? -1 : т.indexOf('\n};', н);
  if (н < 0 || к < 0) return null;
  try { return (0, eval)('(' + т.slice(н + 'const Д ='.length, к + 2) + ')'); } catch { return null; }
}
const глубже = (з, чис, стр) => {
  if (typeof з === 'number') return чис(з);
  if (typeof з === 'string') return стр ? стр(з) : з;
  if (Array.isArray(з)) return з.map(x => глубже(x, чис, стр));
  if (з && typeof з === 'object') { const о = {}; for (const [k, v] of Object.entries(з)) о[k] = глубже(v, чис, стр); return о; }
  return з;
};

const Д = договорные();
if (!Д) { console.error('НЕ РАЗОБРАЛИСЬ договорные данные из tools/data-check.js — покрытие потеряно, прогон остановлен'); process.exit(1); }

/* Мутант и минус нужны не для красоты: только на них срабатывают записи
   «зажато», «не влезло», «не сходится» и «ниже оси» — те самые виды,
   ради чисел которых поле «замечания» и заводилось нарядом 24. Без них
   схема записи осталась бы объявленной, но не поверенной ни разу. */
/* Пустая строка — законная подача: поле прислали, но оставили пустым.
   Библиотека принимает такое за «не передано» и дорисовывает образцом —
   на этом наборе срабатывают виды «взято из образца» и «дополнено_образцом». */
const пустыеСтроки = д => глубже(д, v => v, () => '');
/* Каждому массиву дописана его же копия. Договор рассчитан на своё число
   рядов, лишние отрисовка отбрасывает, — на этом наборе срабатывает вид
   «не нарисовано». */
const удвоить = з => {
  if (Array.isArray(з)) { const у = з.map(удвоить); return [...у, ...у]; }
  if (з && typeof з === 'object') { const о = {}; for (const [k, v] of Object.entries(з)) о[k] = удвоить(v); return о; }
  return з;
};

const НАБОРЫ = [
  { имя: 'образец',        дать: э => э.образец },
  { имя: 'договорные',     дать: э => Д[э.ид] ?? null },
  { имя: 'мутант',         дать: э => Д[э.ид] ? глубже(Д[э.ид], v => v * 3 + 7, s => s + ' и уточнение по отделу для полноты картины') : null },
  { имя: 'минус',          дать: э => Д[э.ид] ? глубже(Д[э.ид], v => -Math.abs(v) - 13, null) : null },
  { имя: 'пустые строки',  дать: э => Д[э.ид] ? пустыеСтроки(Д[э.ид]) : null },
  { имя: 'удвоенные ряды', дать: э => Д[э.ид] ? удвоить(Д[э.ид]) : null },
  { имя: 'чужое поле',     дать: () => ({ 'такогополянет': 'значение' }) }
];

