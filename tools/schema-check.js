const КОРЕНЬ = new URL('../', import.meta.url);
const путь = о => new URL(о, КОРЕНЬ).pathname.replace(/^\/([A-Za-z]:)/, '$1');

const ЭЛЕМЕНТЫ = CATS.flatMap(([, л]) => л.map(([ид, , , обр]) => ({ ид, образец: обр ?? null })));
