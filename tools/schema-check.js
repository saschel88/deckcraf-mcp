const { tools } = await клиент.listTools();
const схемы = new Map(tools.map(т => [т.name, т.outputSchema]));
const судья = new AjvJsonSchemaValidator();
const проверятели = new Map();
for (const [имя, сх] of схемы) if (сх) проверятели.set(имя, судья.getValidator(сх));

/* Канонический вид: ключи по порядку, вложенно. Сличение строкой без него
   зависело бы от порядка ключей — а важно, не переписана ли вторая сторона. */
const канон = з => {
  if (Array.isArray(з)) return '[' + з.map(канон).join(',') + ']';
  if (з && typeof з === 'object') return '{' + Object.keys(з).sort().map(к => JSON.stringify(к) + ':' + канон(з[к])).join(',') + '}';
  return JSON.stringify(з) ?? 'null';
};

let вызовов = 0, сверок = 0;
const беды = [];            // не больше первых N печатаем, но считаем все
const веткиВстречены = new Map();
const видыЗамечаний = new Map();
const отметить = (карта, что) => карта.set(что, (карта.get(что) || 0) + 1);

async function сверить(имя, арг, метка, ждёмОтказ = false) {
  вызовов++;
  let р;
  try { р = await клиент.callTool({ name: имя, arguments: арг }); }
  catch (e) { беды.push(`${метка}: клиент SDK отверг ответ — ${e.message}`); return null; }

  if (р.isError) {
    сверок++;
    if (!ждёмОтказ) { беды.push(`${метка}: отказ там, где ждали результат — ${String(р.content?.[0]?.text).slice(0, 90)}`); return р; }
    if (р.structuredContent !== undefined) беды.push(`${метка}: при isError пришёл structuredContent`);
    else if (!(р.content?.[0]?.type === 'text' && р.content[0].text.length > 10)) беды.push(`${метка}: причина отказа не читается текстом`);
    else отметить(веткиВстречены, `${имя}: отказ`);
    return р;
  }
  if (ждёмОтказ) { беды.push(`${метка}: ждали отказ, пришёл результат`); return р; }

  const сх = схемы.get(имя);
  if (!сх) { беды.push(`${метка}: outputSchema не объявлена`); return р; }
  if (!(р.structuredContent && typeof р.structuredContent === 'object' && !Array.isArray(р.structuredContent))) {
    беды.push(`${метка}: structuredContent не пришёл объектом`); return р;
  }
  сверок++;
  const в = проверятели.get(имя)(р.structuredContent);
  if (!в.valid) беды.push(`${метка}: ${в.errorMessage}`);

  /* Дублирование, а не перенос — сторожится и здесь, на каждой ветке. */
  const блок = р.content?.[0];
  if (!(блок && блок.type === 'text' && блок.text)) беды.push(`${метка}: content опустел или не текстовый`);
  else {
    let изТекста;
    try { изТекста = JSON.parse(блок.text); } catch (e) { беды.push(`${метка}: content не разбирается — ${e.message}`); }
    if (изТекста !== undefined && канон(изТекста) !== канон(р.structuredContent))
      беды.push(`${метка}: content и structuredContent разошлись`);
  }
  return р;
}

const ветка = (о, имя) => { отметить(веткиВстречены, имя); return о; };

await ветка(await сверить('styles', {}, 'styles'), 'styles');
await ветка(await сверить('catalog', {}, 'catalog: стиль не выбран'), 'catalog: стиль не выбран');
for (const к of РАЗДЕЛЫ)
  await ветка(await сверить('catalog', { category: к }, `catalog/${к}: фильтр без стиля`), 'catalog: фильтр по разделу');
await ветка(await сверить('catalog', { category: 'нетакогораздела' }, 'catalog: раздела нет', true), 'catalog: отказ');
await сверить('find', { query: 'воронка' }, 'find до start', true);
await сверить('describe', { id: 'kpi' }, 'describe до start', true);
await сверить('draw', { id: 'kpi' }, 'draw до start', true);

for (const ст of СТИЛИ) {
  await ветка(await сверить('start', { style: ст }, `start/${ст}`), 'start');
  await ветка(await сверить('catalog', {}, `catalog/${ст}`), 'catalog: стиль выбран');
  for (const к of РАЗДЕЛЫ) await сверить('catalog', { category: к }, `catalog/${ст}/${к}`);
  await ветка(await сверить('find', { query: 'воронка отсев кандидатов по этапам' }, `find/${ст}`), 'find: кандидаты найдены');
  await ветка(await сверить('find', { query: 'ъъъщщщэээ' }, `find/${ст}: пусто`), 'find: ничего не совпало');

  for (const э of ЭЛЕМЕНТЫ) {
    await ветка(await сверить('describe', { id: э.ид }, `describe/${ст}/${э.ид}`), 'describe: элемент описан');
    if (!годен(э.ид, ст)) { await сверить('draw', { id: э.ид }, `draw/${ст}/${э.ид}`, true); continue; }
    await ветка(await сверить('draw', { id: э.ид }, `draw/${ст}/${э.ид}`), 'draw: без данных');
    for (const н of НАБОРЫ) {
      const д = н.дать(э);
      if (д === null || д === undefined) continue;
      const р = await сверить('draw', { id: э.ид, data: д }, `draw/${ст}/${э.ид}/${н.имя}`);
      отметить(веткиВстречены, 'draw: с данными');
      for (const з of (р?.structuredContent?.['замечания'] || [])) отметить(видыЗамечаний, String(з?.['вид']));
    }
  }
}
