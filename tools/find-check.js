const зов = async (и, а = {}) => JSON.parse((await клиент.callTool({ name: и, arguments: а })).content[0].text);
await зов('start', { style: 'flat' });

const места = new Map();                       // запрос → место ожидаемого элемента

async function прогон(название, ЗАПРОСЫ) {
  let первым = 0, втройке = 0;
  const мимо = [];
  for (const [запрос, ждём] of ЗАПРОСЫ) {
    const о = await зов('find', { query: запрос });
    const ид = (о['кандидаты'] || []).map(к => к['id']);
    места.set(запрос, ид.indexOf(ждём) + 1);
    if (ид[0] === ждём) первым++;
    else if (ид.includes(ждём)) втройке++;
    else мимо.push(`«${запрос}» — ждём ${ждём}, дал ${ид.join(', ') || 'ничего'}`);
  }
  console.log(`${название}: запросов ${ЗАПРОСЫ.length}, первым ${первым}, в тройке ещё ${втройке}, мимо ${мимо.length}`);
  if (мимо.length) { console.log('  не нашлись:'); мимо.forEach(м => console.log('    · ' + м)); }
  return { первым, всего: ЗАПРОСЫ.length, мимо };
}

