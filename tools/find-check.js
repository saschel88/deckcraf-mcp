const просели = [], поднялись = [], пропали = [];
for (const [запрос, доМесто] of ДО_ПРАВКИ_ИМЁН) {
  if (!места.has(запрос)) { пропали.push(запрос); continue; }
  const после = места.get(запрос);
  if (после === 1) первымПосле++;
  if (после === доМесто) continue;
  const строка = `«${запрос}»: было ${доМесто || 'мимо'}, стало ${после || 'мимо'}`;
  (после === 0 || (доМесто !== 0 && после > доМесто) ? просели : поднялись).push(строка);
}
